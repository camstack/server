#!/usr/bin/env tsx
/**
 * Codegen: emit `SCOPE_PRESETS` — operator-facing scope bundles that
 * fill the admin UI's ScopePicker in one click.
 *
 * Presets are derived from the cap registry (via `METHOD_ACCESS_MAP`)
 * so a newly-added `scope: 'device'` cap is automatically picked up by
 * `camera-viewer` / `camera-operator` on the next codegen pass. No
 * hand-maintained allowlist.
 *
 * Three preset shapes:
 *
 *   - `category:device` rows — broadest. New device caps inherit. Used
 *     by `camera-viewer` (view) and `camera-operator` (view+create).
 *   - `capability:<name>` rows — specific cap grants. Used by
 *     `cli-deployer` (addons cap) etc.
 *   - Mixed — `event-listener` carries a few `capability:*` rows
 *     because we don't want to grant ALL device caps, just the
 *     event-emitting subset.
 *
 * Operators can always edit / add rows after picking a preset; the
 * preset is a "fill the form" UI helper, not an opaque reference.
 */

import * as fs from 'node:fs'
import { writeIfChanged } from './codegen-write.ts'
import * as path from 'node:path'
import { PRESETS, type PresetRow } from './scope-preset-specs.ts'

const ROOT = path.resolve(import.meta.dirname ?? __dirname, '..')
const OUTPUT_FILE = path.join(ROOT, 'packages/types/src/generated/scope-presets.ts')

function quote(s: string): string {
  return JSON.stringify(s)
}

function renderRow(r: PresetRow): string {
  const access = `[${r.access.map(quote).join(', ')}]`
  return `{ type: ${quote(r.type)}, target: ${quote(r.target)}, access: ${access} }`
}

function main(): void {
  const banner = `/**
 * AUTO-GENERATED by scripts/generate-scope-presets.ts — DO NOT EDIT.
 *
 * Pre-baked scope bundles for the admin UI's ScopePicker. Each preset
 * is a list of rows that an admin can drop into a user / token grant.
 * Edit the preset definitions in the generator script, not here.
 */
import type { TokenScope } from '../schemas/auth-records.js'

export interface ScopePresetSpec {
  readonly id: string
  readonly label: string
  readonly description: string
  readonly rows: readonly TokenScope[]
}

export const SCOPE_PRESETS: readonly ScopePresetSpec[] = [
${PRESETS.map(
  (p) => `  {
    id: ${quote(p.id)},
    label: ${quote(p.label)},
    description: ${JSON.stringify(p.description)},
    rows: [
${p.rows.map((r) => `      ${renderRow(r)},`).join('\n')}
    ],
  },`,
).join('\n')}
] as const

export type ScopePresetId = ${PRESETS.map((p) => quote(p.id)).join(' | ')}
`

  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true })
  writeIfChanged(OUTPUT_FILE, banner)
  // eslint-disable-next-line no-console
  console.log(`Wrote ${PRESETS.length} preset(s) → ${path.relative(ROOT, OUTPUT_FILE)}`)
}

main()
