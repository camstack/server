#!/usr/bin/env tsx
/**
 * Catalog-licence guard — a model CamStack can download declares, in the
 * catalog, what it is and on what terms (D661).
 *
 * ## The failure this catches
 *
 * On 2026-09-26 the `license` field existed and was filled on 12 of 77
 * entries; the public model repository had no licence file at all. Nothing
 * refused either. The facts were re-derived by hand, from ONNX metadata and
 * upstream READMEs, and three catalog comments turned out to be wrong.
 *
 * ## What it checks (built-in catalogs only; custom models are the operator's)
 *
 * 1. Every entry has `license.weights`, `.upstream`, `.url`, `.hosting`.
 * 2. An entry CamStack hosts (`camstack-hf`) states `modifications` — Apache
 *    §4(b), GPL/AGPL §5(a) and the Apple AMLR all require the notice.
 * (Model Studio's curated plugin catalog and plus catalog catalogs are walked too.)
 * 3. A `nonCommercial` entry is listed in NON_COMMERCIAL_ACCEPTED with the
 *    reason it is still shipped. A new one cannot slip in unnoticed, and a
 *    line whose entry is gone must be deleted.
 * 4. One upstream name ⇒ one weights licence and one licence URL across every
 *    catalog (the records are duplicated per addon; they may not drift).
 * 5. Every CamStack-mirror folder a catalog downloads from has a model card:
 *    `hf/camstack-models/<category>/<model>/README.md`, or — for the folders
 *    whose card is written by their build script and uploaded with the
 *    weights — a `MODEL_CARD` in that script (CARDS_IN_BUILD_SCRIPTS).
 *
 * Usage: tsx scripts/check-catalog-licence.ts
 */
import { existsSync, readFileSync } from 'node:fs'
import * as path from 'node:path'
import { builtInCatalogEntries, hostedFolders } from './lib/model-catalogs.js'

const ROOT = path.resolve(import.meta.dirname, '..')

/** Non-commercial weights CamStack still ships, and why. Removing a model removes its line. */
export const NON_COMMERCIAL_ACCEPTED: Readonly<Record<string, string>> = {
  'vehicle-type-v1':
    'operator 2026-09-26: kept with the CC BY-NC attribution of its training data (D661)',
}

/** Mirror folders whose model card is generated by the build script that uploads the weights. */
export const CARDS_IN_BUILD_SCRIPTS: Readonly<Record<string, string>> = {
  'faceDetection/yunet': 'scripts/build-yunet-model.py',
  'clip/siglip2': 'scripts/build-siglip2-model.py',
  'plateDetection/yolox-tiny-plate': 'scripts/build-yolox-plate-model.py',
}

/** Floor on the walk: a catalog that silently drops out of it must not read as "all clean". */
const MIN_ENTRIES = 106

interface Problem {
  readonly id: string
  readonly what: string
}

interface UpstreamClaim {
  readonly weights: string
  readonly url: string
  readonly id: string
}

function hasCard(folder: string): boolean {
  if (existsSync(path.join(ROOT, 'hf/camstack-models', folder, 'README.md'))) return true
  const script = CARDS_IN_BUILD_SCRIPTS[folder]
  if (script === undefined) return false
  const abs = path.join(ROOT, script)
  return existsSync(abs) && readFileSync(abs, 'utf8').includes('MODEL_CARD')
}

function main(): void {
  const entries = builtInCatalogEntries().map((r) => r.entry)
  const problems: Problem[] = []
  const byUpstream = new Map<string, UpstreamClaim>()
  const folders = new Set<string>()

  if (entries.length < MIN_ENTRIES) {
    problems.push({
      id: 'catalog walk',
      what: `found ${entries.length} entries, expected at least ${MIN_ENTRIES} — a catalog dropped out of scripts/lib/model-catalogs.ts`,
    })
  }

  for (const e of entries) {
    const l = e.license
    if (!l?.weights || !l.upstream || !l.url || !l.hosting) {
      problems.push({
        id: e.id,
        what: 'license must declare weights, upstream, url and hosting',
      })
      continue
    }
    if (l.hosting === 'camstack-hf' && !l.modifications) {
      problems.push({
        id: e.id,
        what: 'hosted by CamStack but states no modifications',
      })
    }
    if (l.nonCommercial === true && NON_COMMERCIAL_ACCEPTED[e.id] === undefined) {
      problems.push({
        id: e.id,
        what: 'non-commercial weights not listed in NON_COMMERCIAL_ACCEPTED (add it with a reason, or do not ship it)',
      })
    }
    const seen = byUpstream.get(l.upstream.name)
    if (seen && (seen.weights !== l.weights || seen.url !== l.url)) {
      problems.push({
        id: e.id,
        what: `upstream "${l.upstream.name}" disagrees with ${seen.id} on weights/url`,
      })
    } else if (!seen) {
      byUpstream.set(l.upstream.name, {
        weights: l.weights,
        url: l.url,
        id: e.id,
      })
    }
    for (const f of hostedFolders(e)) folders.add(f)
  }

  for (const id of Object.keys(NON_COMMERCIAL_ACCEPTED)) {
    const entry = entries.find((e) => e.id === id)
    if (entry === undefined) {
      problems.push({
        id,
        what: 'listed in NON_COMMERCIAL_ACCEPTED but no longer in any catalog — delete the line',
      })
    } else if (entry.license?.nonCommercial !== true) {
      problems.push({
        id,
        what: 'listed in NON_COMMERCIAL_ACCEPTED but its licence is not marked nonCommercial — delete the line or fix the record',
      })
    }
  }

  for (const folder of folders) {
    if (!hasCard(folder)) {
      problems.push({
        id: folder,
        what: `mirror folder has no model card at hf/camstack-models/${folder}/README.md`,
      })
    }
  }

  if (problems.length > 0) {
    console.error('\n✗ catalog licence: incomplete declarations\n')
    for (const p of problems) console.error(`  ${p.id}: ${p.what}`)
    process.exit(1)
  }
  console.log(
    `✓ catalog licence: ${entries.length} entries declare their terms; ${folders.size} mirror folders have cards`,
  )
}

main()
