#!/usr/bin/env tsx
/**
 * Codegen: generate a typed map from cap name → its status type for
 * every capability that declares a `status` block.
 *
 * The output file `packages/types/src/generated/cap-status-types.ts`
 * powers:
 *   - `CapNameWithStatus` — exhaustive union of cap names that have
 *     a typed status, used as a `deviceManager.subscribeDeviceStatusAggregate`
 *     input constraint so callers can't ask for unknown caps
 *   - `CapStatusTypeMap` — lookup from `capName` → status type, used
 *     by the React hook `useDeviceStatusAggregate` to infer positional
 *     tuple return types from `['battery', 'ptz'] as const`
 *
 * Usage: `npx tsx scripts/generate-cap-status-types.ts`
 *
 * Run alongside `generate-cap-routers.ts` and `generate-api-types.ts`
 * whenever a cap is added, removed, or its `status` shape changes.
 */

import * as fs from 'node:fs'
import { writeIfChanged } from './codegen-write.ts'
import * as path from 'node:path'
import type { CapabilityDefinition } from '../packages/types/src/capabilities/capability-definition.js'

const ROOT = path.resolve(import.meta.dirname ?? __dirname, '..')
const CAPS_DIR = path.join(ROOT, 'packages/types/src/capabilities')
const OUTPUT_FILE = path.join(ROOT, 'packages/types/src/generated/cap-status-types.ts')

interface CapStatusInfo {
  fileName: string // 'battery.cap'
  exportName: string // 'batteryCapability'
  statusSchemaExport: string | null // 'BatteryStatusSchema' when exported separately
  capName: string // 'battery'
  kind: string // 'push' | 'poll' | 'command-driven' | 'unknown'
}

function kebabToCamel(str: string): string {
  return str.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())
}

function kebabToPascal(str: string): string {
  const camel = kebabToCamel(str)
  return camel.charAt(0).toUpperCase() + camel.slice(1)
}

async function loadCapsWithStatus(): Promise<CapStatusInfo[]> {
  const files = fs.readdirSync(CAPS_DIR).filter((f) => f.endsWith('.cap.ts'))
  const out: CapStatusInfo[] = []

  for (const file of files) {
    const filePath = path.join(CAPS_DIR, file)
    // eslint-disable-next-line @typescript-eslint/no-unsafe-assignment
    const mod: Record<string, unknown> = await import(filePath)
    const exportName = Object.keys(mod).find((k) => k.endsWith('Capability'))
    if (!exportName) continue
    const capDef = mod[exportName] as CapabilityDefinition
    if (!capDef.status) continue

    // Heuristic: find a sibling schema export matching the cap's
    // expected name pattern, e.g. 'battery' → 'BatteryStatusSchema'.
    // We use that EXPORTED schema when available to keep the generated
    // file dependency-minimal; otherwise we fall back to pulling the
    // schema inline from the cap export at runtime.
    const pascal = kebabToPascal(capDef.name)
    const expectedSchemaName = `${pascal}StatusSchema`
    const schemaExport = Object.prototype.hasOwnProperty.call(mod, expectedSchemaName)
      ? expectedSchemaName
      : null

    out.push({
      fileName: file.replace(/\.ts$/, ''),
      exportName,
      statusSchemaExport: schemaExport,
      capName: capDef.name,
      kind: capDef.status.kind ?? 'unknown',
    })
  }
  out.sort((a, b) => a.capName.localeCompare(b.capName))
  return out
}

function generate(caps: readonly CapStatusInfo[]): string {
  const lines: string[] = []
  lines.push('/* AUTO-GENERATED by scripts/generate-cap-status-types.ts. DO NOT EDIT. */')
  lines.push('/* eslint-disable */')
  lines.push('')
  lines.push(`import type { z } from 'zod'`)
  lines.push('')
  for (const c of caps) {
    // Only import the cap def when we need to index its inline status
    // schema. When the cap file exports a named `<Pascal>StatusSchema`
    // we import that instead — keeps the generated file slimmer and
    // avoids "unused import" lint errors.
    const imports: string[] = []
    if (c.statusSchemaExport) imports.push(c.statusSchemaExport)
    else imports.push(c.exportName)
    // `import type`: these schemas/cap-defs are used ONLY inside `z.infer<typeof X>` below (type
    // positions). A value import would drag every status cap-def schema into every runtime that
    // touches the `@camstack/types` barrel (via the value export `CAP_NAMES_WITH_STATUS`), bloating
    // each addon runner's heap for no runtime need. The `no-value-cap-import-in-status-types` guard
    // (scripts/check-cap-status-type-imports.ts) fails the build if this regresses to a value import.
    lines.push(`import type { ${imports.join(', ')} } from '../capabilities/${c.fileName}.js'`)
  }
  lines.push('')
  lines.push('/**')
  lines.push(' * Lookup from cap name (literal) → the TypeScript type of that')
  lines.push(" * capability's `status.schema`. Populated at codegen time from every")
  lines.push(' * `*.cap.ts` file that declares a `status` block.')
  lines.push(' */')
  lines.push('export type CapStatusTypeMap = {')
  for (const c of caps) {
    // Two-path inference:
    //   - If we found a sibling exported schema name, infer from it directly
    //     (cheaper & stable for Zod's type resolver).
    //   - Otherwise, index into the cap def's nested status.schema.
    if (c.statusSchemaExport) {
      lines.push(`  readonly '${c.capName}': z.infer<typeof ${c.statusSchemaExport}>`)
    } else {
      lines.push(`  readonly '${c.capName}': z.infer<(typeof ${c.exportName})['status']['schema']>`)
    }
  }
  lines.push('}')
  lines.push('')
  lines.push('/** Union of every cap name that has a typed status block. */')
  lines.push('export type CapNameWithStatus = keyof CapStatusTypeMap')
  lines.push('')
  lines.push('/**')
  lines.push(' * Runtime list of cap names with status. Used by the settings')
  lines.push(' * aggregator to enumerate caps whose `status` should be polled +')
  lines.push(' * streamed via `subscribeDeviceStatusAggregate`.')
  lines.push(' */')
  lines.push('export const CAP_NAMES_WITH_STATUS = [')
  for (const c of caps) {
    lines.push(`  '${c.capName}',`)
  }
  lines.push('] as const satisfies readonly CapNameWithStatus[]')
  lines.push('')
  return lines.join('\n')
}

async function main(): Promise<void> {
  const caps = await loadCapsWithStatus()
  const code = generate(caps)
  fs.mkdirSync(path.dirname(OUTPUT_FILE), { recursive: true })
  writeIfChanged(OUTPUT_FILE, code)
  // eslint-disable-next-line no-console
  console.log(
    `cap-status-types: ${caps.length} cap(s) with status → ${path.relative(ROOT, OUTPUT_FILE)}`,
  )
  for (const c of caps) {
    // eslint-disable-next-line no-console
    console.log(`  ${c.capName} (kind=${c.kind})`)
  }
}

main().catch((err) => {
  // eslint-disable-next-line no-console
  console.error('generate-cap-status-types: failed —', err)
  process.exit(1)
})
