#!/usr/bin/env tsx
/**
 * Codegen: emit a constant `CAP_PROVIDER_KIND_MAP` that lists every
 * capability whose definition carries `providerKind: <ProviderKind>`.
 *
 * This map powers the unified admin UI "Integrations" page
 * (`/system/integrations`): the page enumerates the entries, groups
 * them by `ProviderKind`, and renders one section per kind. A future
 * addon that ships a new external-system cap (e.g. HomeKit) only
 * needs to tag its cap with `providerKind: 'device-export'` — the
 * page will pick it up automatically on the next codegen pass.
 *
 * Output: `packages/types/src/generated/provider-kind-map.ts`
 *
 * Run manually: npx tsx scripts/generate-provider-kind-map.ts
 */

import * as fs from 'node:fs'
import { writeIfChanged } from './codegen-write.ts'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseAllCaps } from './lib/parse-cap.js'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const CAPS_DIR = path.join(ROOT, 'packages/types/src/capabilities')
const OUTPUT = path.join(ROOT, 'packages/types/src/generated/provider-kind-map.ts')

function quote(s: string): string {
  return JSON.stringify(s)
}

async function main(): Promise<void> {
  const all = parseAllCaps(CAPS_DIR)
  const tagged = all
    .filter((c) => c.providerKind !== null)
    .slice()
    .sort((a, b) => a.capName.localeCompare(b.capName))

  const entries = tagged.map((c) => `  ${quote(c.capName)}: ${quote(c.providerKind!)},`).join('\n')

  const banner = `/**
 * AUTO-GENERATED by scripts/generate-provider-kind-map.ts — DO NOT EDIT.
 *
 * Map of capability name → \`ProviderKind\` for every cap that declares
 * \`providerKind\` in its \`.cap.ts\` definition. Consumed by the admin
 * UI's unified Integrations page to enumerate every external-system
 * provider cap and group it by kind. Adding a new cap with
 * \`providerKind\` set lights up its section on that page automatically
 * — no manual registry edit required.
 *
 * Coverage: ${tagged.length} capabilities tagged with providerKind.
 */
`

  const body = `import type { ProviderKind } from '../capabilities/capability-definition.js'

export const CAP_PROVIDER_KIND_MAP: Readonly<Record<string, ProviderKind>> = Object.freeze({
${entries}
} as const)

/** Every cap name tagged with a \`providerKind\`. */
export const PROVIDER_KIND_CAP_NAMES: readonly string[] = [
${tagged.map((c) => `  ${quote(c.capName)},`).join('\n')}
] as const

/**
 * Return every cap name registered under a given \`ProviderKind\`.
 * Stable insertion order (alphabetical by cap name).
 */
export function getCapsByProviderKind(kind: ProviderKind): readonly string[] {
  const out: string[] = []
  for (const [capName, capKind] of Object.entries(CAP_PROVIDER_KIND_MAP)) {
    if (capKind === kind) out.push(capName)
  }
  return out
}
`

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
  writeIfChanged(OUTPUT, banner + body)
  // eslint-disable-next-line no-console
  console.log(`Wrote ${tagged.length} provider-kind entries → ${path.relative(ROOT, OUTPUT)}`)
}

main().catch((err: unknown) => {
  // eslint-disable-next-line no-console
  console.error(err)
  process.exit(1)
})
