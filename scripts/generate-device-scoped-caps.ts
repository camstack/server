#!/usr/bin/env tsx
/**
 * Codegen: emit `DEVICE_SCOPED_CAPS` — the names of every `scope: 'device'`
 * capability, as plain data.
 *
 * WHY THIS EXISTS (runner footprint, D28): a notification rule can ACTUATE a
 * device, and the only boundary on what it may reach is "the capability must be
 * device-scoped". That check runs inside `addon-post-analysis`, which is a
 * FORKED RUNNER — and importing `ALL_CAPABILITY_DEFINITIONS` to ask a cap for
 * its scope eagerly constructs the Zod graph of every cap, ~144MB RSS per
 * runner. Exactly the cost `COLLECTION_ARRAY_METHODS` exists to avoid; this is
 * the same trick for a different one-bit question.
 *
 * Authoritative: derived by reading `scope` off the REAL cap definitions at
 * codegen time, never hand-maintained. A cap that stops being device-scoped
 * leaves this list in the same change — which is what makes the boundary
 * unable to rot into a stale allowlist.
 *
 * Output: `packages/types/src/generated/device-scoped-caps.ts`
 *
 * Run manually: npx tsx scripts/generate-device-scoped-caps.ts
 */

import * as fs from 'node:fs'
import * as path from 'node:path'
import { fileURLToPath } from 'node:url'
import { ALL_CAPABILITY_DEFINITIONS } from '../packages/types/src/generated/capability-router-map.ts'
import { writeIfChanged } from './codegen-write.ts'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const ROOT = path.resolve(__dirname, '..')
const OUTPUT = path.join(ROOT, 'packages/types/src/generated/device-scoped-caps.ts')

async function main(): Promise<void> {
  const names = ALL_CAPABILITY_DEFINITIONS.filter((d) => d.scope === 'device')
    .map((d) => d.name)
    .sort()

  const banner = `/**
 * AUTO-GENERATED by scripts/generate-device-scoped-caps.ts — DO NOT EDIT.
 *
 * Every \`scope: 'device'\` capability name, as plain data — so a forked runner
 * can answer "may a rule actuate this?" without importing the schema barrel
 * (~144MB RSS per runner, D28).
 *
 * Coverage: ${names.length} device-scoped capabilities.
 */
`

  const body = `export const DEVICE_SCOPED_CAPS: ReadonlySet<string> = new Set([
${names.map((n) => `  ${JSON.stringify(n)},`).join('\n')}
])

/**
 * True when \`capName\` is a device capability.
 *
 * This is the ONLY boundary on what a notification rule may actuate. A rule can
 * be authored by a non-admin and the runner executes with the addon's
 * privileges, so an unbounded action would be an arbitrary RPC channel with a
 * privilege escalation attached. Device scope excludes the system caps
 * (\`device-manager.removeDevice\` and friends) by construction.
 */
export function isDeviceScopedCap(capName: string): boolean {
  return DEVICE_SCOPED_CAPS.has(capName)
}
`

  fs.mkdirSync(path.dirname(OUTPUT), { recursive: true })
  writeIfChanged(OUTPUT, banner + body)
  // eslint-disable-next-line no-console
  console.log(`Wrote ${names.length} device-scoped caps → ${path.relative(ROOT, OUTPUT)}`)
}

main().catch((err: unknown) => {
  // eslint-disable-next-line no-console
  console.error(err)
  process.exit(1)
})
