// ── Workspace model ────────────────────────────────────────────────────────

/** One addon declared inside a package manifest's `camstack.addons[]`. */
interface AddonManifest {
  readonly id: string
  readonly category: string
  readonly placement: string
  readonly group: string | null
  readonly instanceMode: string | null
  readonly capabilities: readonly string[]
  /** `@camstack/system` builtin that opted out of running in hub-main. */
  readonly isolate: boolean
  /** The package the manifest came from — decides in-process vs own runner. */
  readonly packageName: string
}

/** A workspace package as the docs care about it. */
interface PackageInfo {
  readonly dir: string
  readonly name: string
  readonly version: string
  readonly private: boolean
  /** `camstack.system: true` — host-provided, cannot be uninstalled. */
  readonly system: boolean
  readonly description: string
  readonly addons: readonly AddonManifest[]
}

type PackageRole = 'framework' | 'addon' | 'tooling' | 'app'

function readJson(file: string): Record<string, unknown> {
  const parsed: unknown = JSON.parse(fs.readFileSync(file, 'utf-8'))
  return parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)
    ? (parsed as Record<string, unknown>)
    : {}
}

function asString(value: unknown, fallback: string): string {
  return typeof value === 'string' ? value : fallback
}

function asRecord(value: unknown): Record<string, unknown> | null {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : null
}

function parseAddonManifests(
  camstack: Record<string, unknown> | null,
  packageName: string,
): AddonManifest[] {
  if (!camstack) return []
  const raw = camstack['addons']
  if (!Array.isArray(raw)) return []
  const out: AddonManifest[] = []
  for (const entry of raw) {
    const addon = asRecord(entry)
    if (!addon) continue
    const execution = asRecord(addon['execution'])
    const capsRaw = addon['capabilities']
    const capabilities: string[] = []
    if (Array.isArray(capsRaw)) {
      for (const cap of capsRaw) {
        const capRecord = asRecord(cap)
        if (capRecord && typeof capRecord['name'] === 'string') capabilities.push(capRecord['name'])
      }
    }
    out.push({
      id: asString(addon['id'], '(unnamed)'),
      category: asString(addon['category'], '—'),
      placement: execution ? asString(execution['placement'], 'any-node') : 'any-node',
      group: execution && typeof execution['group'] === 'string' ? execution['group'] : null,
      instanceMode: typeof addon['instanceMode'] === 'string' ? addon['instanceMode'] : null,
      capabilities: capabilities.toSorted(),
      isolate: execution?.['isolate'] === true,
      packageName,
    })
  }
  return out
}

/** Every workspace package under `packages/` + `server/`, flat one level. */
function collectPackages(): PackageInfo[] {
  const out: PackageInfo[] = []
  for (const root of ['packages', 'server']) {
    const rootDir = path.join(ROOT, root)
    if (!fs.existsSync(rootDir)) continue
    for (const entry of fs.readdirSync(rootDir, { withFileTypes: true }).toSorted()) {
      if (!entry.isDirectory()) continue
      const pkgJson = path.join(rootDir, entry.name, 'package.json')
      if (!fs.existsSync(pkgJson)) continue
      const pkg = readJson(pkgJson)
      const camstack = asRecord(pkg['camstack'])
      out.push({
        dir: `${root}/${entry.name}`,
        name: asString(pkg['name'], `${root}/${entry.name}`),
        version: asString(pkg['version'], '—'),
        private: pkg['private'] === true,
        system: camstack !== null && camstack['system'] === true,
        description: asString(pkg['description'], ''),
        addons: parseAddonManifests(camstack, asString(pkg['name'], `${root}/${entry.name}`)),
      })
    }
  }
  return out
}

/** `@camstack/*` dependencies of the root package = the shipped closure. */
function rootClosureDeps(): ReadonlySet<string> {
  const pkg = readJson(path.join(ROOT, 'server', 'backend', 'package.json'))
  const deps = asRecord(pkg['dependencies']) ?? {}
  return new Set(Object.keys(deps).filter((d) => d.startsWith('@camstack/')))
}

/**
 * Role classification, DERIVED — no hand-kept list to rot.
 *
 * Deliberately keyed off the root package's dependency closure rather than the
 * `camstack.system` manifest flag, because the two disagree: `types` and `sdk`
 * declare `camstack.system: false` yet are framework by every
 * operational measure (the image's own seed script excludes exactly
 * `system,types,sdk,ui-library` from the addon seed — Dockerfile:76).
 * The flag means "surface it in the Admin UI's un-uninstallable section"; the
 * closure means "this is how the code reaches a node". Roles follow the latter.
 *
 * Order matters: `system` itself is in the closure AND declares 19 addon
 * manifests (the builtins), so the framework test has to win first.
 */
function roleOf(pkg: PackageInfo, closure: ReadonlySet<string>): PackageRole {
  if (pkg.dir.startsWith('server/')) return 'app'
  const inClosure = closure.has(pkg.name)
  if (inClosure && (pkg.system || pkg.addons.length === 0)) return 'framework'
  if (pkg.addons.length > 0) return 'addon'
  return 'tooling'
}

/**
 * How a package's code actually reaches a running node — the distinction that
 * decides whether `Update all` (a root-package install) picks a change up, or
 * whether it needs `camstack deploy`.
 */
function shipsVia(pkg: PackageInfo, role: PackageRole, closure: ReadonlySet<string>): string {
  if (role === 'app') return 'the update itself'
  if (role === 'framework') return '`@camstack/server` closure'
  // The Publish Packages workflow skips exactly `private: true` packages, so the
  // manifest alone says whether a tool is on npm — no registry call in a generator.
  if (role === 'tooling') return pkg.private ? 'not published (private)' : 'npm, standalone tool'
  return closure.has(pkg.name) ? 'addons dir (image-seeded)' : 'addons dir'
}

// ── Renderers ──────────────────────────────────────────────────────────────

function mdTable(headers: readonly string[], rows: readonly (readonly string[])[]): string {
  const head = `| ${headers.join(' | ')} |`
  const sep = `| ${headers.map(() => '---').join(' | ')} |`
  const body = rows.map((r) => `| ${r.join(' | ')} |`).join('\n')
  return [head, sep, body].join('\n')
}

function code(value: string): string {
  return value.length > 0 ? `\`${value}\`` : '—'
}

function renderPackages(pkgs: readonly PackageInfo[]): string {
  const closure = rootClosureDeps()
  const byRole = (role: PackageRole): PackageInfo[] =>
    pkgs.filter((p) => roleOf(p, closure) === role)
  const section = (title: string, note: string, rows: readonly PackageInfo[]): string =>
    [
      `## ${title} (${rows.length})`,
      '',
      note,
      '',
      mdTable(
        ['Package', 'Directory', 'Version', 'Reaches a node via', 'What it is'],
        rows.map((p) => [
          code(p.name),
          code(p.dir),
          p.private ? '_private_' : p.version,
          shipsVia(p, roleOf(p, closure), closure),
          p.description.length > 0 ? p.description.replaceAll('|', '\\|') : '—',
        ]),
      ),
      '',
    ].join('\n')

  return [
    BANNER,
    '# Packages',
    '',
    `${pkgs.length} workspace packages. Roles are derived: \`camstack.system: true\` →`,
    'framework; a `camstack.addons[]` entry → addon; `server/*` → the root app;',
    'everything else → tooling.',
    '',
    section(
      'App',
      'The single root package every node boots. Hub vs agent is `CAMSTACK_ROLE`, not a different package.',
      byRole('app'),
    ),
    section(
      'Framework',
      [
        'Host-provided: addons do NOT bundle these, they resolve them from the running',
        'closure. Consequence worth knowing: a framework change reaches a node ONLY',
        'through a root-package install (`applyServerUpdate` / "Update all"), pinned to',
        'the exact version the published `@camstack/server` carries. `camstack deploy`',
        'cannot ship it.',
      ].join(' '),
      byRole('framework'),
    ),
    section(
      'Addons',
      [
        'Each declares one or more `camstack.addons[]` entries and lives in',
        '`<dataDir>/addons/`. Updated with `camstack deploy` (or the Addons page) —',
        'NOT by a root-package update. The ones marked _image-seeded_ are also',
        'dependencies of the root package: the image copies them into the addons dir on',
        'first boot, after which the addons-dir copy is what loads and the closure copy',
        'is inert.',
      ].join(' '),
      byRole('addon'),
    ),
    section('Tooling', 'Build, dev and CLI packages. Not loaded at runtime.', byRole('tooling')),
  ].join('\n')
}

/**
 * Where the addon's code actually executes. A `@camstack/system` builtin is
 * in-process on hub-main by default; `execution.isolate` opts it out.
 */
function addonProcess(addon: AddonManifest): string {
  if (addon.packageName !== '@camstack/system') return 'own runner'
  return addon.isolate ? 'own runner (`isolate`)' : 'hub-main'
}

