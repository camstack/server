/**
 * `--only a,b` restricts generation to those output basenames.
 *
 * It exists for the pre-commit hook, and the reason is measured: the storage map
 * costs 45 of this script's 60 seconds (it parses the whole workspace twice),
 * while the subsystem join costs 0.7. The hook must regenerate the subsystem
 * pages whenever a source file is ADDED or DELETED or a document's frontmatter
 * changes — which is far more commits than a manifest change — and a hook that
 * adds a minute to those commits is a hook people learn to bypass with `-n`.
 */
function onlyFilter(): ReadonlySet<string> | null {
  const index = process.argv.indexOf('--only')
  if (index < 0) return null
  const raw = process.argv[index + 1]
  if (raw === undefined) {
    console.error('✘ --only needs a comma-separated list of output basenames')
    process.exit(2)
  }
  return new Set(raw.split(',').map((s) => s.trim()))
}

function build(): GeneratedFile[] {
  const only = onlyFilter()
  const wanted = (name: string): boolean => only === null || only.has(name)
  const files: GeneratedFile[] = []

  if (wanted('packages.md') || wanted('addons.md') || wanted('capabilities.md')) {
    const pkgs = collectPackages()
    if (wanted('packages.md')) {
      files.push({ file: path.join(OUT_DIR, 'packages.md'), content: renderPackages(pkgs) })
    }
    if (wanted('addons.md')) {
      files.push({ file: path.join(OUT_DIR, 'addons.md'), content: renderAddons(pkgs) })
    }
    if (wanted('capabilities.md')) {
      files.push({
        file: path.join(OUT_DIR, 'capabilities.md'),
        content: renderCapabilities(parseAllCaps(CAPS_DIR), pkgs),
      })
    }
  }
  if (wanted('guards.md')) {
    files.push({ file: path.join(OUT_DIR, 'guards.md'), content: renderGuards(collectGuards()) })
  }
  if (wanted('storage.md')) {
    files.push({
      file: path.join(OUT_DIR, 'storage.md'),
      content: renderStorage(buildStorageMap(ROOT, SETTINGS_BACKEND), buildDurableCatalogue(ROOT)),
    })
  }
  // The subsystem index. Its ONE hand-written input is `docs/subsystems.yaml`;
  // both pages below are joins over it, the workspace and doc frontmatter.
  //
  // The file universe is the CACHED one (`git ls-files --cached`), never the
  // working tree. `--check` runs in CI against a fresh clone where nothing is
  // untracked, so a page counting the author's un-added scratch files could
  // never match and the docs job would be red on every machine but one. At
  // pre-commit time `--cached` is also exactly right: it is what the commit will
  // contain.
  if (wanted('subsystems.md') || wanted('coverage.md')) {
    const subsystems = loadSubsystemMap(ROOT, true)
    if (wanted('subsystems.md')) {
      files.push({
        file: path.join(OUT_DIR, 'subsystems.md'),
        content: renderSubsystemsPage(subsystems, BANNER),
      })
    }
    if (wanted('coverage.md')) {
      files.push({
        file: path.join(OUT_DIR, 'coverage.md'),
        content: renderCoveragePage(subsystems, BANNER),
      })
    }
  }
  // The decision index only exists once there are decisions to index.
  const adrs = wanted('index.md') ? collectAdrs() : []
  if (adrs.length > 0) {
    files.push({
      file: path.join(DECISIONS_DIR, 'index.md'),
      content: renderDecisionIndex(adrs),
    })
  }
  return files
}

function main(): void {
  const checkMode = process.argv.includes('--check')
  const files = build()
  fs.mkdirSync(OUT_DIR, { recursive: true })

  if (!checkMode) {
    for (const { file, content } of files) {
      fs.writeFileSync(file, `${content.trimEnd()}\n`, 'utf-8')
      console.log(`  ✔ ${path.relative(ROOT, file)}`)
    }
    return
  }

  const drifted: string[] = []
  for (const { file, content } of files) {
    const expected = `${content.trimEnd()}\n`
    const actual = fs.existsSync(file) ? fs.readFileSync(file, 'utf-8') : ''
    if (actual !== expected) drifted.push(path.relative(ROOT, file))
  }
  if (drifted.length > 0) {
    console.error('\x1b[31m✘ generated docs are stale\x1b[0m — run `npm run docs:generate`:')
    for (const f of drifted) console.error(`    ${f}`)
    process.exit(1)
  }
  console.log('  ✔ generated docs are in sync')
}

main()
