/**
 * Docs generator — derives every STRUCTURAL page of `docs/reference/` from the
 * repository itself, so the map can never drift from the territory.
 *
 * Why this exists:
 *   The hand-written structure map in `AGENTS.md` listed 9 packages that no
 *   longer existed (`kernel`, `core`, `addon-detection-pipeline`, …) and 8 of
 *   its 24 file references were dead. Nothing failed, because nothing checked.
 *   The fix is not "be more disciplined": it is to stop writing by hand what
 *   can be read from the workspace.
 *
 * What is generated (never edit these by hand — the pre-commit hook and CI
 * both overwrite them):
 *   docs/reference/packages.md      every workspace package + its role
 *   docs/reference/addons.md        every addon manifest entry
 *   docs/reference/capabilities.md  every `*.cap.ts` + who provides it
 *   docs/reference/guards.md        every `scripts/check-*` guard + is CI running it
 *   docs/reference/subsystems.md    the curated chapters × what claims them
 *   docs/reference/coverage.md      the same join, pivoted by unit of code
 *   docs/decisions/index.md         the ADR log, from each ADR's own frontmatter
 *
 * What is NOT generated: intent. Architecture explanations, decisions (ADRs)
 * are human/agent prose, guarded separately by
 * `check-docs-drift.ts` (dead-path + staleness checks).
 *
 * Usage:
 *   npm run docs:generate          — write the files
 *   npm run docs:generate -- --check   — fail if what is on disk differs
 *                                        (CI drift guard; used by docs:check)
 */
