/**
 * The UI pointers send Codex, Cursor and Claude Code to the one source of the
 * UI rules. They are generated so they cannot drift — which only holds if the
 * splice is idempotent, never touches the rest of a hand-written AGENTS.md,
 * and the check sees a missing or edited block.
 */
import * as fs from 'node:fs'
import * as os from 'node:os'
import * as path from 'node:path'
import { afterEach, describe, expect, it } from 'vitest'
import {
  blockBegin,
  blockEnd,
  CLAUDE_IMPORT,
  extractBlock,
  planPointers,
  renderBlock,
  renderMdc,
  spliceBlock,
  staleWrites,
} from '../skills/lib/pointer-blocks.js'
import {
  scannedUiRoots,
  UI_BLOCK_ID,
  uiAgentsTargets,
  uiBlock,
  uiMdcTargets,
  uiPointerLines,
} from '../skills/lib/ui-pointers.js'

const REPO = path.resolve(import.meta.dirname, '..', '..')

describe('the UI block', () => {
  it('is 6–10 lines between its markers and names the umbrella skill', () => {
    for (const kind of ['root', 'admin', 'library', 'page', 'agent-ui'] as const) {
      const lines = uiPointerLines(kind)
      expect(lines.length).toBeGreaterThanOrEqual(6)
      expect(lines.length).toBeLessThanOrEqual(10)
      expect(lines.join('\n')).toContain('camstack-ui')
      expect(lines.join('\n')).toContain('ui:check')
    }
  })

  it('never says "generated by scripts/", which would make the docs drift guard skip the whole file', () => {
    expect(renderBlock(uiBlock('root'))).not.toMatch(/generated by `?scripts\//i)
  })

  it('splices idempotently and leaves the rest of the file alone', () => {
    const before = '# AGENTS.md\n\nHand-written rules.\n\n## More\n\nText.\n'
    const once = spliceBlock(before, uiBlock('page'))
    expect(once.startsWith(before.trimEnd())).toBe(true)
    expect(spliceBlock(once, uiBlock('page'))).toBe(once)
  })

  it('replaces only what is between the markers', () => {
    const text = `intro\n${blockBegin(UI_BLOCK_ID)}\nstale line\n${blockEnd(UI_BLOCK_ID)}\noutro\n`
    const next = spliceBlock(text, uiBlock('root'))
    expect(next.startsWith('intro\n')).toBe(true)
    expect(next.endsWith('\noutro\n')).toBe(true)
    expect(extractBlock(next, UI_BLOCK_ID)).toBe(renderBlock(uiBlock('root')))
  })

  it('rewrites a block whose begin marker names an older generator path', () => {
    const old = `<!-- camstack-${UI_BLOCK_ID}:begin — written by \`npx tsx scripts/ui/gen-ui-pointers.ts\`; edit the generator, not this block -->`
    const text = `intro\n${old}\nstale\n${blockEnd(UI_BLOCK_ID)}\n`
    const next = spliceBlock(text, uiBlock('root'))
    expect(next).toBe(`intro\n${renderBlock(uiBlock('root'))}\n`)
  })
})

describe('the UI Cursor rules', () => {
  it('are valid .mdc frontmatter: description, comma-separated globs, alwaysApply false', () => {
    const [requested, admin] = uiMdcTargets(REPO)
    const text = renderMdc(admin!)
    const front = /^---\n([\s\S]*?)\n---\n/.exec(text)?.[1] ?? ''
    expect(front).toMatch(/^description: \S/m)
    expect(front).toMatch(/^globs: packages\/addon-admin-ui\/src\/\*\*, /m)
    expect(front).toMatch(/^alwaysApply: false$/m)
    expect(text).toContain('@.claude/skills/camstack-ui-admin/SKILL.md')
    // The agent-requested rule has no globs at all.
    expect(renderMdc(requested!)).not.toMatch(/^globs:/m)
  })

  it('auto-attach to every tree the admin-ui stylesheet scans', () => {
    const css = '@source "../../ui-library/src";\n@source "../../addon-benchmark/src";\n'
    expect(scannedUiRoots(css)).toEqual(['packages/ui-library/src', 'packages/addon-benchmark/src'])
    const admin = uiMdcTargets(REPO).find((t) => t.file.endsWith('camstack-ui-admin.mdc'))
    expect(admin?.globs).toContain('packages/addon-model-studio/src/**')
  })
})

describe('UI targets and the check', () => {
  const tmp: string[] = []
  afterEach(() => {
    for (const d of tmp.splice(0)) fs.rmSync(d, { recursive: true, force: true })
  })

  function fixture(): string {
    const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ui-pointers-'))
    tmp.push(root)
    fs.writeFileSync(path.join(root, 'AGENTS.md'), '# AGENTS.md\n\nRoot rules.\n')
    fs.mkdirSync(path.join(root, 'packages/addon-admin-ui/src'), { recursive: true })
    fs.writeFileSync(
      path.join(root, 'packages/addon-admin-ui/src/index.css'),
      '@source "../../ui-library/src";\n@source "../../addon-shop/src";\n',
    )
    fs.mkdirSync(path.join(root, 'packages/addon-shop'), { recursive: true })
    fs.writeFileSync(path.join(root, 'packages/addon-shop/CLAUDE.md'), '@AGENTS.md\n')
    return root
  }

  const plan = (root: string) =>
    planPointers(root, uiAgentsTargets(['addon-shop']), uiMdcTargets(root))

  it('covers the root, admin-ui, ui-library, agent-ui and every page package once', () => {
    const files = uiAgentsTargets(['addon-shop', 'addon-agent-ui']).map((t) => t.file)
    expect(files).toEqual([
      'AGENTS.md',
      'packages/addon-admin-ui/AGENTS.md',
      'packages/ui-library/AGENTS.md',
      'packages/addon-agent-ui/AGENTS.md',
      'packages/addon-shop/AGENTS.md',
    ])
  })

  it('creates a missing package AGENTS.md and its CLAUDE.md import, and keeps an existing CLAUDE.md', () => {
    const root = fixture()
    const { writes, problems } = plan(root)
    expect(problems).toEqual([])
    const byFile = new Map(writes.map((w) => [w.file, w.content]))
    expect(byFile.get('packages/addon-shop/AGENTS.md')).toContain(renderBlock(uiBlock('page')))
    expect(byFile.get('packages/ui-library/CLAUDE.md')).toBe(CLAUDE_IMPORT)
    expect(byFile.has('packages/addon-shop/CLAUDE.md')).toBe(false)
    expect(byFile.get('AGENTS.md')).toContain('Root rules.')
  })

  it('reports nothing stale once written, and a hand edit inside a block as stale', () => {
    const root = fixture()
    for (const w of plan(root).writes) {
      fs.mkdirSync(path.dirname(path.join(root, w.file)), { recursive: true })
      fs.writeFileSync(path.join(root, w.file), w.content)
    }
    expect(staleWrites(root, plan(root).writes)).toEqual([])

    const agents = path.join(root, 'packages/addon-shop/AGENTS.md')
    fs.writeFileSync(
      agents,
      fs.readFileSync(agents, 'utf8').replace('Search before', 'Maybe search'),
    )
    expect(staleWrites(root, plan(root).writes).map((w) => w.file)).toEqual([
      'packages/addon-shop/AGENTS.md',
    ])
  })

  it('refuses a CLAUDE.md that does not import AGENTS.md rather than overwrite it', () => {
    const root = fixture()
    fs.writeFileSync(path.join(root, 'packages/addon-shop/CLAUDE.md'), '# my own notes\n')
    expect(plan(root).problems).toEqual([
      'packages/addon-shop/CLAUDE.md exists and does not import @AGENTS.md — fix it by hand',
    ])
  })
})
