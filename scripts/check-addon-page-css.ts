#!/usr/bin/env tsx
/**
 * Addon-page CSS guard — every addon page's Tailwind classes ship in the
 * admin-ui stylesheet (D747).
 *
 * ## The failure this catches
 *
 * An addon page (`camstack.addons[].pages` in its package.json) is a Module
 * Federation remote. `AddonPageLoader` loads its JavaScript and nothing else:
 * the page's own compiled CSS (`dist/<pkg>.css`) is never requested. So every
 * utility class the page uses must already exist in the HOST stylesheet, and
 * Tailwind writes a class into that stylesheet only if it finds it in a file
 * it scans. `packages/addon-admin-ui/src/index.css` scanned ui-library and
 * three widget trees — not the page packages. A class that admin-ui or the
 * library happened to use elsewhere rendered; one that only a page used
 * (`gap-x-8`, `pl-1`, `bg-zinc-*` on Model Studio → Installed) silently
 * produced no rule, and the Installed card drew its Size label on top of its
 * format pills. Nothing failed: the build, the typecheck and the page's own
 * dev server (which loads its own CSS) were all green.
 *
 * Loading the remote's CSS instead was rejected: it is a second full Tailwind
 * build (preflight, theme tokens, and Model Studio's `color-scheme: dark`)
 * injected over the host's, which would fight the light theme.
 *
 * ## What it checks
 *
 * 1. `index.css` carries a generated block with one `@source` per package that
 *    declares an addon page — discovered from every `packages/* /package.json`,
 *    never a hand list — and nothing else (a stale entry fails too).
 * 2. A page package's CSS declares no `@theme` / `@utility` /
 *    `@custom-variant`: those define classes only the page's own build has,
 *    and the host build never reads the page's CSS.
 *
 * `--write` regenerates the block. Usage:
 *   tsx scripts/check-addon-page-css.ts [--write]
 */
import * as fs from 'node:fs'
import * as path from 'node:path'

const ROOT = path.resolve(import.meta.dirname, '..')
const PACKAGES = path.join(ROOT, 'packages')
export const HOST_CSS = 'packages/addon-admin-ui/src/index.css'

export const BLOCK_BEGIN =
  '/* addon-page-sources:begin — generated by `tsx scripts/check-addon-page-css.ts --write`; do not edit */'
export const BLOCK_END = '/* addon-page-sources:end */'

/** Directives that mint classes inside a CSS file the host never reads. */
const PAGE_ONLY_DIRECTIVES = /@(theme|utility|custom-variant)\b/

interface PackageJsonShape {
  readonly camstack?: { readonly addons?: readonly { readonly pages?: readonly unknown[] }[] }
}

function isPackageJsonShape(value: unknown): value is PackageJsonShape {
  return typeof value === 'object' && value !== null
}

/** True when a package.json declares at least one addon page. */
export function declaresAddonPage(pkg: unknown): boolean {
  if (!isPackageJsonShape(pkg)) return false
  return (pkg.camstack?.addons ?? []).some((a) => Array.isArray(a.pages) && a.pages.length > 0)
}

/** Package directory names (under `packages/`) that declare an addon page, sorted. */
export function pagePackages(packagesDir: string = PACKAGES): readonly string[] {
  return fs
    .readdirSync(packagesDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .filter((name) => {
      const file = path.join(packagesDir, name, 'package.json')
      if (!fs.existsSync(file)) return false
      return declaresAddonPage(JSON.parse(fs.readFileSync(file, 'utf8')))
    })
    .toSorted()
}

/** The generated block for `packages`, as it must appear in `index.css`. */
export function expectedBlock(packages: readonly string[]): string {
  return [BLOCK_BEGIN, ...packages.map((p) => `@source "../../${p}/src";`), BLOCK_END].join('\n')
}

/** The block currently in `css`, or `null` when the markers are missing. */
export function currentBlock(css: string): string | null {
  const begin = css.indexOf(BLOCK_BEGIN)
  const end = css.indexOf(BLOCK_END)
  if (begin < 0 || end < begin) return null
  return css.slice(begin, end + BLOCK_END.length)
}

/** Why `css` does not cover exactly `packages` (empty ⇒ covered). */
export function coverageProblems(css: string, packages: readonly string[]): readonly string[] {
  const block = currentBlock(css)
  if (block === null) return [`${HOST_CSS} has no addon-page-sources block`]
  const listed = [...block.matchAll(/@source "\.\.\/\.\.\/([^/"]+)\/src";/g)].map((m) => m[1])
  const missing = packages
    .filter((p) => !listed.includes(p))
    .map((p) => `page package not scanned: ${p}`)
  const stale = listed
    .filter((p): p is string => p !== undefined && !packages.includes(p))
    .map((p) => `scanned package declares no page: ${p}`)
  const drift =
    block === expectedBlock(packages) || missing.length + stale.length > 0
      ? []
      : ['block is not in generated form']
  return [...missing, ...stale, ...drift]
}

/** `@theme` / `@utility` / `@custom-variant` declarations in a page package's CSS. */
export function pageOnlyClassDefinitions(cssFiles: readonly { file: string; css: string }[]) {
  return cssFiles.filter((f) => PAGE_ONLY_DIRECTIVES.test(f.css)).map((f) => f.file)
}

function cssFilesUnder(dir: string): readonly string[] {
  if (!fs.existsSync(dir)) return []
  return fs
    .readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter((d) => d.isFile() && d.name.endsWith('.css'))
    .map((d) => path.join(d.parentPath, d.name))
}

function main(): void {
  const write = process.argv.includes('--write')
  const packages = pagePackages()
  const hostFile = path.join(ROOT, HOST_CSS)
  const css = fs.readFileSync(hostFile, 'utf8')
  if (write) {
    const block = currentBlock(css)
    const next =
      block === null
        ? `${css.trimEnd()}\n\n${expectedBlock(packages)}\n`
        : css.replace(block, expectedBlock(packages))
    fs.writeFileSync(hostFile, next)
    console.log(`wrote ${packages.length} addon page source(s) into ${HOST_CSS}`)
    return
  }
  const problems = [...coverageProblems(css, packages)]
  for (const p of packages) {
    if (!fs.existsSync(path.join(PACKAGES, p, 'src')))
      problems.push(`page package has no src/: ${p}`)
    const files = cssFilesUnder(path.join(PACKAGES, p, 'src')).map((file) => ({
      file: path.relative(ROOT, file),
      css: fs.readFileSync(file, 'utf8'),
    }))
    for (const file of pageOnlyClassDefinitions(files)) {
      problems.push(
        `${file} defines classes (@theme/@utility/@custom-variant) the host build never reads`,
      )
    }
  }
  if (problems.length > 0) {
    console.error(
      'check-addon-page-css: addon page classes would not ship in the admin-ui stylesheet',
    )
    for (const p of problems) console.error(`  - ${p}`)
    console.error(
      'Fix: tsx scripts/check-addon-page-css.ts --write (and move page-only CSS into ui-library)',
    )
    process.exit(1)
  }
  console.log(
    `check-addon-page-css: ${packages.length} addon page package(s) scanned by ${HOST_CSS}`,
  )
}

if (process.argv[1] && import.meta.url === `file://${process.argv[1]}`) main()
