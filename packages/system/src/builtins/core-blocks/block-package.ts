/**
 * Turning a stored block into something the addon runner can fork.
 *
 * The runner already knows how to do everything a block needs — fork a
 * process, build the full UDS `ctx`, redirect host-provided imports, and hand
 * the whole thing to `CrashSupervisor` (D6). What it does NOT know how to do is
 * load code out of a database row: `addon-runner` reads a package.json off
 * disk. So a block is MATERIALISED as a minimal addon package and spawned like
 * any other addon. No second runner, no second supervisor, no `node:vm`.
 *
 * Two files are generated per block:
 *
 *   `dist/block.js` — the author's TypeScript, transpiled.
 *   `dist/index.js` — a generated wrapper that adapts the author's contract
 *                     (`export default (ctx) => disposer`) to `ICamstackAddon`.
 *
 * The wrapper exists so the author never writes `super({})`, which is the trap
 * that killed `CoreBlocksAddon` in production while the build stayed green and
 * the topology reported it running.
 */

import * as fs from 'node:fs/promises'
import * as path from 'node:path'
import {
  CORE_BLOCK_ADDON_PREFIX,
  type ConfigUISchema,
  coreBlockAddonId,
  coreBlockIdFromAddonId,
} from '@camstack/types'

/**
 * The runner id lives on the CAPABILITY, not here.
 *
 * It stopped being an implementation detail the day the operator surface
 * started reading a block's logs by asking `logs.query` for
 * `addonId = core-block-<id>` — with no cap of its own. A second copy of the
 * string would drift into a logs pane that is silently always empty, so these
 * are re-exports under the names this package already used.
 */
export const BLOCK_ADDON_PREFIX: string = CORE_BLOCK_ADDON_PREFIX
export const blockAddonId: typeof coreBlockAddonId = coreBlockAddonId
export const blockIdFromAddonId: typeof coreBlockIdFromAddonId = coreBlockIdFromAddonId

export interface MaterializeBlockInput {
  /** Root under which every block package lives — one directory per block. */
  readonly root: string
  readonly blockId: string
  readonly blockName: string
  /** The block's bundled / transpiled JavaScript (written to `dist/block.js`). */
  readonly js: string
  /**
   * Optional TypeScript sources (path → content). Written under `src/` so a
   * multi-file project is inspectable on disk next to the bundle the runner
   * loads. Absent for a legacy single-file materialize.
   */
  readonly files?: Readonly<Record<string, string>>
  /** The block's settings form: its secret fields are keychain-backed at runtime (D880). */
  readonly settingsSchema?: ConfigUISchema | undefined
}

export interface MaterializedBlock {
  /** What `$process.spawnRunner` gets as `addonDir` — the package root. */
  readonly addonDir: string
  readonly addonId: string
}

/**
 * The wrapper module, generated verbatim.
 *
 * A string rather than a file copied from `dist` because it must land NEXT to
 * the author's code inside the block package: the runner imports one entry, and
 * relative imports have to resolve inside that directory.
 *
 * Three things it guarantees, all of them failures this repo has already paid
 * for once:
 *
 *  - `super({})` is here, so no author can omit it;
 *  - a module with no default function FAILS LOUDLY with the block's name in
 *    the message, instead of starting a process that does nothing;
 *  - the disposer is awaited on shutdown, so a block that owns a timer or a
 *    socket releases it on `setEnabled(false)` rather than on the next reboot.
 */
const WRAPPER_SOURCE = `// GENERATED by @camstack/system core-blocks. Do not edit — rewritten on every
// deploy of the block it wraps.
import { BaseAddon } from '@camstack/types'
// NAMESPACE import, not \`import blockMain from\`. A default import of a module
// that has no default export is a LINK-time SyntaxError: the module never
// executes, so the friendly check below would never run and the author would
// get a bare Node stack trace naming neither their block nor the mistake.
// Verified, not assumed — a test spawns exactly that module.
import * as blockModule from './block.js'

const BLOCK_ID = __BLOCK_ID__
const BLOCK_NAME = __BLOCK_NAME__
// The block's settings form, embedded so the SDK derives the keychain secret
// tree from it (a password field is stored as a marker and read back resolved,
// D880). null = the block declares none.
const BLOCK_SETTINGS_SCHEMA = __BLOCK_SETTINGS_SCHEMA__
const blockMain = blockModule.default

export default class CoreBlockAddon extends BaseAddon {
  constructor() {
    // NOT optional: BaseAddon.resolveConfig reads Object.keys(this.defaults),
    // so omitting this kills the process at init while the topology still
    // reports the addon running.
    super({})
    this.disposer = null
  }

  globalSettingsSchema() {
    return BLOCK_SETTINGS_SCHEMA
  }

  async onInitialize() {
    if (typeof blockMain !== 'function') {
      throw new Error(
        \`core block "\${BLOCK_NAME}" (\${BLOCK_ID}) has no default export function — \` +
          'a block must "export default" a function taking ctx',
      )
    }
    const result = await blockMain(this.ctx)
    this.disposer = typeof result === 'function' ? result : null
    // One line, always. A block that started and does nothing visible is
    // indistinguishable from one that never loaded without it.
    this.ctx.logger.info('core block started', {
      meta: { blockId: BLOCK_ID, name: BLOCK_NAME, hasDisposer: this.disposer !== null },
    })
    return []
  }

  async onShutdown() {
    if (this.disposer === null) return
    const dispose = this.disposer
    this.disposer = null
    await dispose()
  }
}
`

/** Build the wrapper for one block. Exported for the test that asserts the
 *  generated source actually carries the block's identity. */
export function renderBlockWrapper(
  blockId: string,
  blockName: string,
  settingsSchema: ConfigUISchema | undefined = undefined,
): string {
  // Function replacers: a replacement STRING reads `$&`, `$1` ... specially and
  // a schema is arbitrary JSON.
  return WRAPPER_SOURCE.replace('__BLOCK_ID__', () => JSON.stringify(blockId))
    .replace('__BLOCK_NAME__', () => JSON.stringify(blockName))
    .replace('__BLOCK_SETTINGS_SCHEMA__', () => JSON.stringify(settingsSchema ?? null))
}

/** The package manifest the addon runner reads to find the entry point. */
export function renderBlockManifest(blockId: string, blockName: string): string {
  return `${JSON.stringify(
    {
      name: `@camstack/${blockAddonId(blockId)}`,
      version: '0.0.0',
      private: true,
      type: 'module',
      main: './dist/index.js',
      camstack: {
        addons: [
          {
            id: blockAddonId(blockId),
            name: blockName,
            category: 'system',
            description: 'A user-authored core block.',
            entry: './dist/index.js',
            capabilities: [],
          },
        ],
      },
    },
    null,
    2,
  )}\n`
}

/**
 * Write (or rewrite) a block's package. Idempotent, and deliberately a full
 * rewrite: the author's code is the thing that changes, and a partial update
 * that left a stale `block.js` behind would run yesterday's code while the
 * editor showed today's.
 *
 * Layout:
 *   `src/<path>`     — author TypeScript when `files` is provided
 *   `dist/block.js`  — bundled / transpiled entry (what the wrapper imports)
 *   `dist/index.js`  — generated BaseAddon wrapper
 */
export async function materializeBlock(input: MaterializeBlockInput): Promise<MaterializedBlock> {
  const addonDir = path.join(input.root, input.blockId)
  const distDir = path.join(addonDir, 'dist')
  const srcDir = path.join(addonDir, 'src')
  // Drop a previous `src/` so a file the author deleted does not linger and
  // look like part of today's project.
  await fs.rm(srcDir, { recursive: true, force: true })
  await fs.mkdir(distDir, { recursive: true })
  if (input.files !== undefined) {
    for (const [rel, content] of Object.entries(input.files)) {
      const abs = path.resolve(srcDir, rel)
      if (!abs.startsWith(srcDir + path.sep) && abs !== srcDir) {
        throw new Error(`refusing path outside the block package: ${rel}`)
      }
      await fs.mkdir(path.dirname(abs), { recursive: true })
      await fs.writeFile(abs, content, 'utf-8')
    }
  }
  await Promise.all([
    fs.writeFile(
      path.join(addonDir, 'package.json'),
      renderBlockManifest(input.blockId, input.blockName),
      'utf-8',
    ),
    fs.writeFile(path.join(distDir, 'block.js'), input.js, 'utf-8'),
    fs.writeFile(
      path.join(distDir, 'index.js'),
      renderBlockWrapper(input.blockId, input.blockName, input.settingsSchema),
      'utf-8',
    ),
  ])
  return { addonDir, addonId: blockAddonId(input.blockId) }
}

/** Remove a block's package. Idempotent — a missing directory is the desired
 *  end state, not an error. */
export async function removeBlockPackage(root: string, blockId: string): Promise<void> {
  await fs.rm(path.join(root, blockId), { recursive: true, force: true })
}
