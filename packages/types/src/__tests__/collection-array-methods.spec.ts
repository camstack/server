import { describe, expect, it } from 'vitest'
import { isCollectionArrayMethod } from '../capabilities/cap-router-predicates.js'
import { expandCapMethods } from '../capabilities/capability-definition.js'
import { ALL_CAPABILITY_DEFINITIONS } from '../generated/capability-router-map.js'
import {
  COLLECTION_ARRAY_METHODS,
  isCollectionArrayMethodName,
} from '../generated/collection-array-methods.js'

/**
 * D28 drift guard. The addon-runner replaced its eager
 * `isCollectionArrayMethod(ALL_CAPABILITY_DEFINITIONS…)` barrel import (+~146MB
 * RSS per forked runner) with the codegen'd, schema-free
 * `isCollectionArrayMethodName` backed by `COLLECTION_ARRAY_METHODS`. The map is
 * generated by running the REAL predicate at codegen time, so it MUST answer
 * identically for every (cap, method) pair — otherwise a runner would silently
 * mis-route a collection method. This test reconstructs the truth from the live
 * cap definitions and asserts the generated lookup matches exactly; it fails the
 * moment codegen is skipped after a `.cap.ts` change.
 */
describe('collection-array-methods generated map (D28)', () => {
  it('matches the real isCollectionArrayMethod for every cap/method pair', () => {
    for (const def of ALL_CAPABILITY_DEFINITIONS) {
      for (const method of Object.keys(expandCapMethods(def))) {
        const truth = isCollectionArrayMethod(def, method)
        expect(
          isCollectionArrayMethodName(def.name, method),
          `${def.name}.${method} — generated map disagrees with predicate (run \`npm run codegen\`)`,
        ).toBe(truth)
      }
    }
  })

  it('lists no cap outside the map that has a collection array method', () => {
    const expected = new Set<string>()
    for (const def of ALL_CAPABILITY_DEFINITIONS) {
      const arrayMethods = Object.keys(expandCapMethods(def)).filter((m) =>
        isCollectionArrayMethod(def, m),
      )
      if (arrayMethods.length > 0) expected.add(def.name)
    }
    expect(new Set(Object.keys(COLLECTION_ARRAY_METHODS))).toEqual(expected)
  })
})
