// Zod 4's `ZodRawShape = $ZodShape = Record<string, $ZodType<unknown, unknown>>`
// is too strict for concrete-shape schemas: a `z.object({ host: z.string(), … })`
// produces `ZodObject<{ host: ZodString, … }>` whose fields' types
// (`ZodString`, `ZodDefault<ZodNumber>`, …) don't widen to
// `$ZodType<unknown, unknown>` once a subclass has 30+ fields, so
// HikvisionCamera fails TS2344 on the constraint.
//
// Zod ships `$ZodLooseShape = Record<string, any>` for exactly this
// pattern — generic constraints that should accept any concrete schema.
// Using it on the type parameter keeps the typed inference path
// (`z.infer<T>`, `T['shape']['host']`) intact while admitting concrete
// schemas from subclasses.
export abstract class BaseDevice<
  T extends z.ZodObject<z.core.$ZodLooseShape> = z.ZodObject<z.ZodRawShape>,
> implements IDevice
{
  readonly id: number
  readonly stableId: string
  readonly type: DeviceType
  readonly name: string
  readonly parentDeviceId: number | null
  readonly role?: DeviceRole
  /**
   * Cap-keyed runtime-state slice is the single source of truth for
   * `online`. Both getter and setter proxy to the slice — drivers can
   * write `this.online = true` ergonomically, and the cap event fires
   * automatically through the runtime-state writer. `markOnline()` is
   * kept as the explicit method form mandated by `IDevice`.
   */
  get online(): boolean {
    const slice = this.runtimeState.getCapState<DeviceStatus>('device-status')
    return slice?.online ?? false
  }
  set online(value: boolean) {
    this.markOnline(value)
  }

  /**
   * Generic per-cap runtime-state namespace. One entry per cap with
   * `runtimeState:` declared, auto-generated by codegen — see
   * `device-local-state.ts`. Drivers access via:
   *
   *   `this.state.battery.sleeping = true`        // patches the battery slice
   *   `const pct = this.state.battery.percentage` // reads the battery slice
   *   `this.state.deviceStatus.online = true`     // mirrors `markOnline(true)`
   *
   * Adding a new cap with `runtimeState:` automatically extends this
   * namespace — drivers don't have to declare proxies. Reads return
   * `undefined` when the slice hasn't been seeded; writes patch via
   * `runtimeState.patchCapState` and validate against the cap's schema
   * (so partial writes need the slice to be seeded with the required
   * fields first — drivers do this on cap registration).
   *
   * For caps not exposed in `DeviceLocalState`, drivers can build their
   * own typed proxy via `this.sliceProxy(cap)`.
   */
  get state(): DeviceLocalState {
    if (!this._stateProxyCache) {
      const cache = {} as DeviceLocalState
      const handler: ProxyHandler<DeviceLocalState> = {
        get: (target, key) => {
          const k = key as keyof DeviceLocalState
          const existing = Reflect.get(target, k)
          if (existing !== undefined) return existing
          const cap = DEVICE_LOCAL_STATE_CAPS[k]
          if (!cap) return undefined
          const proxy = this.sliceProxy(cap)
          Reflect.set(target, k, proxy)
          return proxy
        },
      }
      this._stateProxyCache = new Proxy(cache, handler)
    }
    return this._stateProxyCache
  }
  private _stateProxyCache?: DeviceLocalState
  abstract readonly features: readonly DeviceFeature[]
  readonly config: DeviceConfig<T>
  /**
   * Per-device runtime state, cap-keyed. Always installed — slices
   * for individual caps materialise as those caps register their
   * native providers (`ctx.registerNativeCap`). The cap's own
   * `runtimeState` schema is the source of truth for the slice
   * shape; drivers don't redeclare it, they just write through.
   *
   * Read: `this.runtimeState.getCapState('battery')` →
   *   `{percentage, charging, sleeping, lastUpdated}` for any
   *   provider that registers `batteryCapability`.
   * Write: `this.runtimeState.setCapState('battery', { … })`.
   *
   * Cross-process consumers reach this state through the
   * `deviceState` cap router (or via cap-specific events the driver
   * emits — e.g. `battery.onStatusChanged`). The local handle is
   * accessed in-process by the driver to avoid roundtrips.
   */
  readonly runtimeState: IDeviceRuntimeState
  readonly ctx: DeviceContext

  /**
   * Operator-organisational location label (room / area / zone).
   * Read from `ctx.deviceMeta.location`; mutated via
   * `kernel.devices.setLocation(id, value)`. Free-text — providers
   * don't interpret it; the UI groups devices by this for filters
   * like "show me all cameras in Kitchen". `null` when unset.
   */
  readonly location: string | null
  /**
   * Soft-disabled flag. When `true`, the device class is still
   * instantiated and visible in the UI (so the operator can flip
   * back on without re-adding) but lifecycle hooks (publishToBroker,
   * alarm-stream subscribe, …) MUST be gated by the driver to skip
   * work. The `BaseDevice` enforces this by exposing the flag here;
   * it does NOT mutate cap behaviour automatically — drivers consult
   * `this.disabled` at the top of their lifecycle methods. Read from
   * `ctx.deviceMeta.disabled`; mutated via
   * `kernel.devices.setDisabled(id, value)`.
   */
  readonly disabled: boolean

  /**
   * Cached materialised `SourceInfo` — either the value persisted under
   * `metadata.sourceInfo` at construction time, or a synthetic
   * `{ id: stableId, system: addonId }` for providers that haven't
   * migrated yet. Lazily populated on first `sourceInfo` read so the
   * cost of Zod-parsing the meta blob is paid once per device boot.
   * Invalidated by `updateSourceInfo()` so providers see the new value
   * back through the getter without a re-fetch from the meta surface.
   */
  private _sourceInfoCache: SourceInfo | null = null

  constructor(
    ctx: DeviceContext,
    schema: T,
    options: {
      type: DeviceType
      /** Optional semantic role within parent — see `DeviceRole`. */
      role?: DeviceRole
    },
  ) {
    this.ctx = ctx
    this.id = ctx.id
    this.stableId = ctx.stableId
    this.type = options.type
    // Operator-organisational fields (`name` / `location` / `disabled`)
    // come exclusively from the kernel-managed meta surface. Production
    // contexts always populate `ctx.deviceMeta`; test fixtures must
    // supply it explicitly. No fallback to `options.name` — the only
    // way to set the display name is through the meta API.
    if (!ctx.deviceMeta) {
      throw new Error(
        `BaseDevice constructor: ctx.deviceMeta is required (id=${ctx.id} stableId=${ctx.stableId})`,
      )
    }
    this.name = ctx.deviceMeta.name
    this.location = ctx.deviceMeta.location
    this.disabled = ctx.deviceMeta.disabled
    this.role = options.role
    this.parentDeviceId = ctx.parentDeviceId
    // DeviceContext.persistConfig is typed as (data: unknown) => Promise<void>
    // to break the circular dependency between DeviceContext and every schema type T.
    // DeviceConfig.fromSchema requires (data: z.infer<T>) => Promise<void>, which is a
    // subtype of (data: unknown) => Promise<void> at runtime (TypeScript variance rules
    // prevent direct assignment for function parameters). The wrapper below narrows the
    // type without losing safety — the actual data passed is always z.infer<T> because
    // DeviceConfig itself only calls persistFn with validated T values.
    //
    // Self-hydrate: the kernel pre-loads the per-device persisted
    // config blob from the DB and stuffs it into `ctx.persistedConfig`
    // before this constructor runs. We seed `DeviceConfig` from that
    // blob alone — operator-supplied initial config (Add-Device form
    // input) reaches us via the same DB read because providers
    // pre-persist via `kernel.devices.create(stableId, Class, config)`
    // (or `persistInitialConfig` in the manual flow), which writes
    // the blob to the DB BEFORE constructing the device. The device
    // class therefore never sees an `initialData` constructor arg —
    // every config read goes through `this.config.get(...)` which is
    // a thin in-memory cache over the DB row. Schema defaults fill
    // any missing keys via Zod's parse pass.
    const seedData = ctx.persistedConfig ?? {}
    const declaredSecretPaths = collectZodSecretPaths(schema)
    this.config = DeviceConfig.fromSchema(
      schema,
      // The declared secret paths travel with every persist, so the hub's
      // door keeps those values in the keychain (D787) from the first write
      // this device makes on its own.
      (data: z.infer<T>) => ctx.persistConfig(data, { secretConfigPaths: declaredSecretPaths }),
      seedData,
      ({ droppedKeys, issues }) => {
        // Stale persisted values that no longer match the schema —
        // logged once at boot so operators can see what got reset.
        // The DB blob is healed asynchronously inside `fromSchema`
        // (it persists the cleaned data), so this log is the only
        // visible trace of the recovery path firing.
        ctx.logger.warn('Device config recovery: dropping invalid persisted fields', {
          tags: { deviceId: ctx.id, stableId: ctx.stableId },
          meta: {
            droppedKeys: [...droppedKeys],
            firstIssue: issues[0]?.message ?? null,
          },
        })
      },
    )

    // Always install runtime state — schemas attach lazily as the
    // device's caps register their native providers (see
    // `ctx.registerNativeCap` wiring in the kernel context factory).
    //
    // Writer routes through `fetchDevice(id).deviceState.setCapSlice`
    // so we share the same per-device facade admin-ui + addons use.
    // The DeviceProxy auto-injects deviceId; the dispatch falls
    // through to the local hub provider (or its Moleculer bridge
    // proxy when device-manager runs cross-process).
    //
    // The proxy is fetched lazily on the first write and cached for
    // the device's lifetime — `getBindings` is one cheap query, and
    // `setCapSlice` is a system-cap call that doesn't read binding
    // entries (so cache staleness is irrelevant for this writer).
    let cachedProxy: Promise<import('../generated/device-proxy.js').DeviceProxy> | null = null
    const writer = async (capName: string, slice: Record<string, unknown>): Promise<void> => {
      if (!cachedProxy) cachedProxy = ctx.fetchDevice(ctx.id)
      const dev = await cachedProxy
      await dev.deviceState.setCapSlice({ capName, slice })
    }
    const initial = ctx.initialRuntimeState ?? {}
    // A refused hub write is not mirrored, so nothing downstream sees the
    // slice; the state re-sends it on the next write, and this line is the
    // only trace in between (D391, ruling S6).
    const onWriteFailed = (cap: string, error: string): void => {
      ctx.logger.warn(
        'runtime-state write refused by the hub — the slice is not mirrored; it is re-sent on the next write',
        { tags: { deviceId: ctx.id }, meta: { cap, error } },
      )
    }
    this.runtimeState = DeviceRuntimeState.fromInitial(initial, writer, onWriteFailed)
    // Hand the reference back to the context so subsequent
    // `ctx.registerNativeCap` calls (fired from this constructor's
    // own `registerNativeCapabilities` chain) can install each
    // cap's `runtimeState` schema. Optional hook — test contexts
    // skip it; caps with runtime state in those contexts go memory-
    // only without schema validation.
    ctx.bindRuntimeState?.(this.runtimeState)

    // Auto-register the generic `device-status` cap so every device
    // exposes a uniform cap-keyed slice for the base device-level
    // flags (`online`, `lastChangedAt`). Cross-process consumers read
    // via `device-state.getCapSlice({deviceId, capName: 'device-status'})`
    // instead of having to special-case `online` against the device
    // summary RPC. Driver-specific caps (`battery`, `doorbell`, …)
    // own their own slices.
    ctx.registerNativeCap?.(deviceStatusCapability, {})
    // Seed the slice synchronously so the `online` getter resolves and
    // the first cross-process read returns a populated record. A freshly
    // registered device is PRESUMED reachable (`online: true`) until its
    // driver explicitly marks it offline via `markOnline(false)` (e.g. the
    // Home Assistant addon on an `unavailable` entity). A cold `false`
    // seed would otherwise leave every device whose driver never calls
    // `markOnline(true)` — accessory children (sirens/floodlights/PIR) and
    // never-managed devices — permanently OFFLINE once `listAll` surfaces
    // the real cap-state online flag instead of a hardcoded `true`.
    const seed: DeviceStatus = { online: true, lastChangedAt: Date.now() }
    this.runtimeState.setCapState('device-status', seed)

    // Auto-register the generic `feature-probe` cap. Drivers populate it
    // from `onProbe()` (kernel calls it once after register, before
    // accessory reconciliation). The slice is the single source of truth
    // for `getAccessoryChildren()` decisions and the public `features`
    // array — it replaces the older driver-local `deviceCache.has*`
    // duplication.
    ctx.registerNativeCap?.(featureProbeCapability, {})
    const probeSeed: FeatureProbeStatus = {
      flags: {},
      deviceType: null,
      model: null,
      channelCount: null,
      lastProbedAt: 0,
      lastFetchedAt: 0,
    }
    this.runtimeState.setCapState('feature-probe', probeSeed)
  }

  private readonly deviceActions = new Map<
    string,
    {
      spec: CustomActionSpec
      handler: (input: unknown) => Promise<unknown>
    }
  >()

  /** Declare a device custom action + its typed handler. Idempotent per name. */
  protected registerDeviceAction<TIn extends z.ZodType, TOut extends z.ZodType>(
    name: string,
    spec: CustomActionSpec<TIn, TOut>,
    handler: (input: z.infer<TIn>) => Promise<z.infer<TOut>>,
  ): void {
    this.deviceActions.set(name, {
      spec: spec as CustomActionSpec,
      handler: handler as (i: unknown) => Promise<unknown>,
    })
  }

  /** Invoke a registered device action. Validates input against the spec. */
  async runDeviceAction(action: string, input: unknown): Promise<unknown> {
    const entry = this.deviceActions.get(action)
    if (!entry) throw new Error(`unknown device action "${action}" on device ${this.id}`)
    const parsed = entry.spec.input.parse(input)
    return entry.handler(parsed)
  }

  async removeDevice(): Promise<void> {
    // Override in subclass for cleanup (disconnect, stop streams, etc.)
  }

  /**
   * Set the device's online flag. Called by `BaseDeviceProvider` after
   * aggregating per-profile stream-broker health, or directly by drivers
   * that have provider-side liveness signals (e.g. ONVIF heartbeats,
   * Reolink Baichuan firmware push events). Mirrors the new value into
   * the `device-status` runtime-state slice so cross-process consumers
   * pick it up via the standard cap-state channel. Subclasses can
   * override to gate side effects on the transition.
   */
  markOnline(online: boolean): void {
    if (this.online === online) return
    const next: DeviceStatus = { online, lastChangedAt: Date.now() }
    this.runtimeState.setCapState('device-status', next)
  }

  /**
   * Upstream-system identity + rendering envelope for this device. See
   * `SourceInfo` for the field contract. Always returns a valid object:
   * if the persisted `metadata.sourceInfo` blob is absent or fails Zod
   * validation, falls back to a synthetic `{ id: stableId, system: addonId }`
   * so providers that haven't migrated keep working without code changes.
   *
   * The value is cached after the first read. `updateSourceInfo()`
   * invalidates the cache so subsequent reads see the new patch. The
   * returned object is frozen to prevent accidental in-place mutation —
   * use `updateSourceInfo({ patch })` to change fields.
   */
  get sourceInfo(): Readonly<SourceInfo> {
    if (this._sourceInfoCache) return this._sourceInfoCache
    const fromMeta = extractSourceInfoFromMetadata(this.ctx.deviceMeta.metadata)
    const resolved: SourceInfo =
      fromMeta ??
      synthesizeSourceInfo({
        stableId: this.stableId,
        addonId: this.ctx.deviceMeta.addonId,
      })
    this._sourceInfoCache = Object.freeze({ ...resolved }) as SourceInfo
    return this._sourceInfoCache
  }

  /**
   * Convenience accessor for the upstream dispatch key. Equivalent to
   * `this.sourceInfo.id` — providers use this to keep a
   * `Map<sourceId, IDevice>` for routing inbound push events.
   */
  get sourceId(): string {
    return this.sourceInfo.id
  }

  /**
   * Patch the device's `SourceInfo`. Shallow-merges `patch` over the
   * current value, persists the merged result under
   * `metadata.sourceInfo` via the `device-manager.setMetadata` cap, and
   * emits `EventCategory.DeviceSourceInfoChanged` for live consumers.
   *
   * Safe to call from anywhere in the device's lifetime — the call is
   * idempotent for `undefined` patch values (ignored) and best-effort
   * for persistence (a transient device-manager error doesn't unwind
   * the local cache update, so subsequent reads still see the patch).
   *
   * Drivers populate this on adoption + on every metadata change push
   * from the upstream source. Subscribers (UI, export adapters) react
   * via the `DeviceSourceInfoChanged` event without polling.
   */
  protected async updateSourceInfo(patch: Partial<SourceInfo>): Promise<void> {
    const next = mergeSourceInfo(this.sourceInfo, patch)
    this._sourceInfoCache = Object.freeze({ ...next }) as SourceInfo

    const action = this.ctx.api.deviceManager?.setMetadata
    if (action) {
      try {
        await action.mutate({
          deviceId: this.id,
          patch: { [SOURCE_INFO_METADATA_KEY]: next as Record<string, unknown> },
        })
      } catch {
        // Best-effort persistence — log path requires a logger ref the
        // BaseDevice doesn't keep. The local cache is already updated,
        // so the device stays consistent in-process. Operators see the
        // drift only across a restart, which is a tolerable failure
        // mode for a non-critical metadata field.
      }
    }

    this.ctx.eventBus.emit(
      createEvent(
        'device.source-info-changed',
        { type: 'device', id: this.stableId },
        { deviceId: this.id, sourceInfo: next },
      ),
    )
  }

  /**
   * Re-publish the device's current `features` array to the persisted
   * meta blob. Drivers call this after a probe finishes when the live
   * `features` getter has gained new flags (e.g. `hasIntercom` flips
   * to true → `DeviceFeature.TwoWayAudio` joins the list).
   *
   * Without this, only the construction-time snapshot is written —
   * `deviceManager.registerDevice` is invoked once per boot, so probe-
   * driven additions don't reach the persisted index until the next
   * server restart, and `getDevice` / `listAll` keep returning the
   * stale list for forked-worker devices (whose live IDevice instance
   * is invisible to the hub registry).
   *
   * Idempotent: re-calling with the same features just no-ops on the
   * persisted meta. Best-effort: lookup or write failures are logged
   * at debug and swallowed — the live `device.features` getter is
   * still authoritative within this process, so callers never block
   * device boot on a meta refresh.
   */
  protected async refreshFeatures(): Promise<void> {
    const action = this.ctx.api.deviceManager?.registerDevice
    if (!action) return
    try {
      await action.mutate({
        addonId: this.ctx.deviceMeta.addonId,
        stableId: this.stableId,
        id: this.id,
        type: this.type,
        name: this.name,
        parentDeviceId: this.parentDeviceId,
        features: [...this.features],
        // Empty config — the kernel's registerDevice ignores the field
        // when there's no payload (the per-device store is the
        // canonical source after construction).
        config: {},
      })
    } catch (err) {
      // No logger on BaseDevice (would require ctx wiring) — drivers
      // that want visibility wrap the call themselves.
      void err
    }
  }

  /**
   * Typed read-through to a cap-keyed runtime-state slice. Drivers
   * call `this.getCapSlice(batteryCapability)` and the return type
   * is inferred from the cap's `runtimeState` Zod schema — no string
   * key, no manual generic. Returns `null` when the slice hasn't
   * been written yet (e.g. driver hasn't seeded battery yet).
   */
  protected getCapSlice<TCap extends CapabilityDefinition>(
    cap: TCap,
  ): InferRuntimeState<TCap> | null {
    const slice = this.runtimeState.getCapState(cap.name)
    return (slice as InferRuntimeState<TCap> | undefined) ?? null
  }

  /**
   * Typed writer to a cap-keyed runtime-state slice. Routes through
   * the runtime-state writer (validate → persist → emit cap event).
   * Equivalent to `this.runtimeState.setCapState(cap.name, value)`
   * but with the cap's `runtimeState` schema enforcing the value
   * shape at compile time. Mirrors the symmetry of
   * `getCapSlice` / `setCapSlice` for cross-cap consistency.
   */
  protected setCapSlice<TCap extends CapabilityDefinition>(
    cap: TCap,
    value: InferRuntimeState<TCap> & Record<string, unknown>,
  ): void {
    this.runtimeState.setCapState(cap.name, value)
  }

  /**
   * Field-level read/write proxy over a cap's runtime-state slice.
   * Drivers that want ergonomic per-field access declare:
   *
   * ```ts
   * protected battery = this.sliceProxy(batteryCapability)
   * // …
   * this.battery.sleeping = true        // patches the slice
   * const charging = this.battery.charging  // reads the slice
   * ```
   *
   * Reads return `undefined` when the slice hasn't been seeded yet
   * (cap not registered, or seeded but the field is absent). Writes
   * route through `runtimeState.patchCapState` so the cap's `runtimeState`
   * schema validates the merged result and the cap event fires.
   *
   * Pattern is generic — same shape works for `battery`, `device-status`,
   * `motion`, `doorbell`, anything with a `runtimeState:` schema. Drivers
   * declare one proxy per cap they read/write directly.
   */
  protected sliceProxy<TCap extends CapabilityDefinition>(cap: TCap): InferRuntimeState<TCap> {
    const target: Record<string, unknown> = {}
    const handler: ProxyHandler<Record<string, unknown>> = {
      get: (_, key) => {
        const slice = this.runtimeState.getCapState(cap.name)
        return slice?.[key as string]
      },
      set: (_, key, value: unknown) => {
        this.runtimeState.patchCapState(cap.name, { [key as string]: value })
        return true
      },
      has: (_, key) => {
        const slice = this.runtimeState.getCapState(cap.name)
        return slice ? key in slice : false
      },
      ownKeys: () => {
        const slice = this.runtimeState.getCapState(cap.name)
        return slice ? Object.keys(slice) : []
      },
      getOwnPropertyDescriptor: (_, key) => {
        const slice = this.runtimeState.getCapState(cap.name)
        if (!slice || !(key in slice)) return undefined
        return { configurable: true, enumerable: true, value: slice[key as string] }
      },
    }
    return new Proxy(target, handler) as InferRuntimeState<TCap>
  }

  /**
   * Default empty settings UI. Drivers override this to expose an
   * editable form in the device-details page. Returning an empty sections
   * array signals "nothing to contribute" — the aggregator drops the
   * contribution entirely rather than rendering a blank panel.
   */
  getSettingsUISchema(): ConfigUISchemaWithValues {
    return { sections: [] }
  }

  /**
   * Default write path: forward the flat patch directly to storage.
   * Drivers that project a UI shape different from storage (e.g. `RtspCamera`
   * exposing `mainStreamUrl`/`subStreamUrl` over `streams[]`) override this
   * to reshape before `config.setAll`.
   */
  async applySettingsPatch(patch: Record<string, unknown>): Promise<void> {
    await this.config.setAll(patch)
  }

  // ── Lifecycle hooks ────────────────────────────────────────────────
  //
  // The kernel orchestrates the device lifecycle in distinct phases.
  // Drivers override only the hooks they need:
  //
  //   1. Construct           — `new DeviceClass(ctx)` (sync)
  //   2. RegisterIdentity    — kernel writes meta + id to device-manager
  //   3. Probe               — `onProbe()` populates `feature-probe` slice
  //   4. ReconcileAccessories — kernel calls `getAccessoryChildren()`
  //                             (sees post-probe flags), spawns missing,
  //                             removes orphans, refreshes meta features
  //   5. Activate            — `onActivate()` does "device is live" work:
  //                             broker publish, snapshot tabs, watchdogs
  //
  // Failures in `onProbe` / `onActivate` are logged and swallowed — the
  // device IS already registered; partial init shouldn't unwind the
  // create the caller succeeded at.

  /**
   * Phase 3 — populate device-scoped state needed by downstream phases
   * (accessory reconciliation, public `features` array, optional cap
   * registration). Called ONCE per construction, after register but
   * before `getAccessoryChildren()`.
   *
   * Drivers write the `feature-probe` runtime-state slice via
   * `this.runtimeState.setCapState('feature-probe', {...})` — flag bag
   * is open (Reolink writes `hasPtz/hasIntercom`, Hikvision writes
   * `hasSupplementalLight/hasAlarmIo`, etc).
   *
   * Default: nothing to probe → mark the device PROBED (set `lastProbedAt`) so
   * the kernel treats it as ready immediately. A device that derives its shape
   * from a spec (a container, or an accessory sensor) rather than from a
   * hardware probe has no probe to "complete"; without stamping `lastProbedAt`
   * it would look perpetually un-probed — logging "Initial probe did not
   * complete" on every boot and spinning a pointless retry chain. Drivers that
   * DO probe override this and write their own `feature-probe` slice (including
   * `lastProbedAt`) once their probe actually succeeds.
   */
  async onProbe(): Promise<void> {
    const current = this.runtimeState.getCapState<FeatureProbeStatus>('feature-probe')
    const base: FeatureProbeStatus = current ?? {
      flags: {},
      deviceType: null,
      model: null,
      channelCount: null,
      lastProbedAt: 0,
      lastFetchedAt: 0,
    }
    this.runtimeState.setCapState('feature-probe', { ...base, lastProbedAt: Date.now() })
  }

  /**
   * Phase 5 — fired after the device + its accessories are registered.
   * Drivers publish streams to the broker, kick off background tasks,
   * or subscribe to lib events that need a fully-registered device id.
   *
   * Default: no-op.
   *
   * RENAMED FROM `onCreated` (which still exists for back-compat in this
   * pass). The new name reflects the post-probe, post-accessory contract.
   */
  async onActivate(): Promise<void> {
    /* override in subclass */
  }

  /**
   * Re-run the probe + reconcile accessories + refresh features meta.
   * Drivers call this when device-side state changes (battery cam wakes,
   * firmware update, manual operator trigger).
   *
   * The kernel injects `_kernelReprobe` on registration so this method
   * delegates to the same orchestrator that runs the boot-time phase
   * 3 + 4 sequence. Drivers should NOT override this — they override
   * `onProbe()` instead.
   */
  async reprobe(): Promise<void> {
    if (this._kernelReprobe) await this._kernelReprobe()
    else await this.onProbe()
  }

  /**
   * Kernel-injected callback that runs the full post-probe orchestration
   * (onProbe → registerDevice meta refresh → accessory reconciliation).
   * Set by `device-cap-proxy.register()`. Drivers should not touch this
   * directly — call `reprobe()` instead.
   */
  _kernelReprobe?: () => Promise<void>

  /**
   * Declare accessory child devices the kernel should auto-spawn
   * after `onProbe()` resolves. Each spec fully describes one child
   * — stableId suffix (deterministic per kind for restore-safety),
   * meta (type / name / location), config (initial blob the child
   * self-hydrates), and a factory that constructs the concrete
   * class with whatever closure-captured refs it needs (typically
   * `this` for the parent reference).
   *
   * The kernel handles the rest: allocateDeviceId, persistInitialConfig
   * (skipped on restore when the row already exists),
   * persistInitialMeta, createContext, factory invocation, register,
   * and recursive lifecycle (probe + accessories + activate).
   *
   * Implementations should derive children from
   * `this.runtimeState.getCapState('feature-probe')` (post-probe truth).
   * Drivers can use the `getProbeFlags()` helper to read the flag bag
   * with a typed cast.
   *
   * Answer what you KNOW. A plain array is read as the complete list only
   * while this device is `online` and probed; return
   * `accessoryChildrenUnknown(reason)` whenever you cannot know the list right
   * now (no credentials, parent not connected, a failed or partial read) —
   * the kernel then deletes nothing. Return `accessoryChildrenComplete(list)`
   * to say "connected, and this is the complete list" explicitly. A shrink is
   * deleted only after a second agreeing complete read on a later probe (D49;
   * `packages/system/src/kernel/moleculer/accessory-prune-gate.ts`).
   *
   * Default: no children.
   */
  getAccessoryChildren(): AccessoryChildrenAnswer {
    return []
  }

  /**
   * Read the current feature-probe flag bag with a typed cast. Helper
   * for `getAccessoryChildren()` and `features` getters that derive
   * outputs from the probe results.
   */
  protected getProbeFlags<F extends Record<string, unknown> = Record<string, unknown>>(): F {
    const slice = this.runtimeState.getCapState<FeatureProbeStatus>('feature-probe')
    return (slice?.flags ?? {}) as F
  }

  /**
   * Returns true once `onProbe` has completed at least once
   * (`lastProbedAt > 0`). Drivers gate `getAccessoryChildren()` on this
   * to avoid spawning stale accessories on a fresh device whose probe
   * hasn't landed yet.
   */
  protected hasProbed(): boolean {
    const slice = this.runtimeState.getCapState<FeatureProbeStatus>('feature-probe')
    return (slice?.lastProbedAt ?? 0) > 0
  }
}

/** "I cannot know my accessory children right now" — the kernel prunes nothing. */
export interface AccessoryChildrenUnknown {
  readonly kind: 'unknown'
  /** Why, for the log line (`no credentials`, `cloud not connected`, …). */
  readonly reason: string
  /**
   * Children known to exist even so (e.g. the core device of a cloud
   * container): they are spawned, never used as the list to prune against.
   */
  readonly known?: readonly AccessoryChildSpec[]
}

/** "Connected, and this is the COMPLETE list" — the only answer a prune may follow. */
export interface AccessoryChildrenComplete {
  readonly kind: 'complete'
  readonly children: readonly AccessoryChildSpec[]
}

export type AccessoryChildrenRead = AccessoryChildrenComplete | AccessoryChildrenUnknown

/**
 * What `getAccessoryChildren()` may answer: a typed read, or a plain list
 * (complete only while the parent is online and probed).
 */
export type AccessoryChildrenAnswer = readonly AccessoryChildSpec[] | AccessoryChildrenRead

export function accessoryChildrenUnknown(
  reason: string,
  known?: readonly AccessoryChildSpec[],
): AccessoryChildrenUnknown {
  return known === undefined ? { kind: 'unknown', reason } : { kind: 'unknown', reason, known }
}

export function accessoryChildrenComplete(
  children: readonly AccessoryChildSpec[],
): AccessoryChildrenComplete {
  return { kind: 'complete', children }
}

/**
 * Specification for one accessory child a parent device wants the
 * kernel to auto-spawn. Returned from `BaseDevice.getAccessoryChildren()`.
 */
export interface AccessoryChildSpec {
  /**
   * Stable suffix appended to the parent's stableId to derive the
   * child's stableId (e.g. `siren` → `${parent.stableId}-siren`).
   * Must be deterministic per (parent, accessory kind) so restore
   * resolves the same numeric id and re-instantiates without
   * orphaning the persisted config.
   */
  readonly stableIdSuffix: string
  /** Operator-organisational meta passed to `kernel.devices.create()`'s
   *  `initialMeta` arg. The kernel pre-writes the meta row before
   *  the child class constructor runs. */
  readonly meta: import('./device-management.js').InitialDeviceMeta
  /** Initial config blob the child self-hydrates from on first
   *  create. Empty `{}` on restore (DB row carries the canonical
   *  values) — the kernel detects the existing row and skips the
   *  pre-persist step. */
  readonly config: Record<string, unknown>
  /**
   * Constructor closure — invoked with the kernel-built context
   * after meta + config are persisted. Closures over the parent
   * reference for child classes that need `parent` as a constructor
   * arg (e.g. accessories that share the parent's connection). The
   * returned IDevice is registered + `onCreated`-fired by the
   * kernel.
   */
  readonly factory: (ctx: DeviceContext) => IDevice
}
