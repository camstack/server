export type DeviceNameLocale = 'en' | 'it'

function findNoun(list: readonly DeviceNounSpec[], id: string | null): DeviceNounSpec | undefined {
  if (id === null || id.length === 0) return undefined
  return list.find((spec) => spec.id === id)
}

/** Role wins when it has a noun; otherwise the type. Unknown types fall back. */
export function nounSpecFor(role: string | null, type: string): DeviceNounSpec {
  if (role !== null) {
    const byRole = findNoun(DEVICE_ROLE_NOUNS, role)
    if (byRole !== undefined) return byRole
  }
  return findNoun(DEVICE_TYPE_NOUNS, type) ?? FALLBACK_NOUN
}

function stockPhrases(role: string | null, type: string): readonly string[] {
  const phrases: string[] = []
  const specs = [findNoun(DEVICE_ROLE_NOUNS, role), findNoun(DEVICE_TYPE_NOUNS, type)]
  for (const spec of specs) {
    if (spec === undefined) continue
    phrases.push(spec.en, spec.it, spec.shortEn, spec.shortIt, ...spec.aliases)
  }
  return phrases
}

export function isDeviceNameStock(text: string, role: string | null, type: string): boolean {
  const folded = foldDeviceName(text)
  if (folded.length === 0) return true
  return stockPhrases(role, type).some((phrase) => foldDeviceName(phrase) === folded)
}

/** Noun table for a locale. Tests and the viewer parity spec use this directly. */
export function deviceNameNouns(locale: DeviceNameLocale): DeviceNameNouns {
  return {
    shortNoun(role: string | null, type: string): string {
      const spec = nounSpecFor(role, type)
      return locale === 'it' ? spec.shortIt : spec.shortEn
    },
    isStockPhrase(text: string, role: string | null, type: string): boolean {
      return isDeviceNameStock(text, role, type)
    },
  }
}
