/**
 * Task 3 RED — bounded frame-lazy telemetry. A production change that would
 * fail this test: per-frame keys, unbounded camera maps, or missing counters.
 */
import { describe, expect, it } from 'vitest'
import { FrameLazyTelemetry, emptyFrameLazyCounters } from '../frame-lazy-metrics.js'

describe('FrameLazyTelemetry', () => {
  it('counts byte/hit/miss/avoided writes/resident refs without cardinality growth', () => {
    const telemetry = new FrameLazyTelemetry()
    telemetry.noteDecoded(1)
    telemetry.noteAdmitted(1)
    telemetry.noteDroppedPixelFree(1)
    telemetry.noteView({ deviceId: 1, materialized: true, workerToRunnerBytes: 4096 })
    telemetry.noteView({ deviceId: 1, materialized: false, workerToRunnerBytes: 0 })
    telemetry.notePoolBytes({ deviceId: 1, raw: 0, jpeg: 2048 })
    telemetry.noteOnDemandRequest({ deviceId: 1, kind: 'full-frame' })
    telemetry.noteOnDemandRequest({ deviceId: 1, kind: 'crop' })
    telemetry.noteHit('native', 1)
    telemetry.noteMiss('native', 1)
    telemetry.noteHit('tile', 1)
    telemetry.noteMiss('tile', 1)
    telemetry.noteHit('fallback', 1)
    telemetry.noteMiss('fallback', 1)
    telemetry.noteAvoidedWrite(1)
    telemetry.noteRelease(1)
    telemetry.noteEviction(1)
    telemetry.noteStale(1)
    telemetry.setResident({ refs: 2, bytes: 128 })

    const snap = telemetry.snapshot([1])
    expect(Object.keys(emptyFrameLazyCounters()).sort()).toEqual(Object.keys(snap.node).sort())
    expect(snap.node.framesDecoded).toBe(1)
    expect(snap.node.framesAdmitted).toBe(1)
    expect(snap.node.framesDroppedPixelFree).toBe(1)
    expect(snap.node.viewsMaterialized).toBe(1)
    expect(snap.node.viewsSkipped).toBe(1)
    expect(snap.node.workerToRunnerBytes).toBe(4096)
    expect(snap.node.runnerToPoolJpegBytes).toBe(2048)
    expect(snap.node.runnerToPoolRawBytes).toBe(0)
    expect(snap.node.onDemandFullFrameRequests).toBe(1)
    expect(snap.node.onDemandCropRequests).toBe(1)
    expect(snap.node.nativeHits).toBe(1)
    expect(snap.node.nativeMisses).toBe(1)
    expect(snap.node.tileHits).toBe(1)
    expect(snap.node.tileMisses).toBe(1)
    expect(snap.node.fallbackHits).toBe(1)
    expect(snap.node.fallbackMisses).toBe(1)
    expect(snap.node.retainedWritesAvoided).toBe(1)
    expect(snap.node.residentRefs).toBe(2)
    expect(snap.node.residentBytes).toBe(128)
    expect(snap.node.releases).toBe(1)
    expect(snap.node.evictions).toBe(1)
    expect(snap.node.staleMisses).toBe(1)
    expect(snap.cameras).toHaveLength(1)
    expect(snap.cameras[0]?.deviceId).toBe(1)

    for (let deviceId = 100; deviceId < 250; deviceId += 1) telemetry.noteDecoded(deviceId)
    const pruned = telemetry.snapshot([1, 100])
    expect(pruned.cameras.map((c) => c.deviceId).sort((a, b) => a - b)).toEqual([1, 100])
    expect(pruned.cameras.length).toBeLessThanOrEqual(2)
    expect(telemetry.trackedCameraCount()).toBeGreaterThan(2)
    for (let deviceId = 101; deviceId < 250; deviceId += 1) telemetry.forgetCamera(deviceId)
    expect(telemetry.trackedCameraCount()).toBe(2)
  })

  it('snapshot does not cancel camera counters; residentRefs is per-camera entry count', () => {
    const telemetry = new FrameLazyTelemetry()
    telemetry.noteAdmitted(1)
    telemetry.noteAdmitted(2)
    telemetry.setResident({ refs: 4, bytes: 800 })
    telemetry.setCameraResident(1, { refs: 3, bytes: 300 })
    telemetry.setCameraResident(2, { refs: 1, bytes: 500 })
    const snap = telemetry.snapshot([1])
    expect(snap.cameras).toHaveLength(1)
    expect(snap.cameras[0]?.residentRefs).toBe(3)
    expect(snap.cameras[0]?.residentBytes).toBe(300)
    expect(snap.node.residentRefs).toBe(4)
    expect(telemetry.trackedCameraCount()).toBe(2)
    telemetry.forgetCamera(2)
    expect(telemetry.trackedCameraCount()).toBe(1)
    const after = telemetry.snapshot([1])
    expect(after.cameras[0]?.framesAdmitted).toBe(1)
    expect(after.cameras[0]?.residentRefs).toBe(3)
  })
})
