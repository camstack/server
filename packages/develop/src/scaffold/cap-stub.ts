import * as fs from 'node:fs'
import * as path from 'node:path'
import { toCapExportName, toClassName, toFileName } from '../naming.js'
import type { ScaffoldCapOptions, ScaffoldCapResult } from '../types.js'

/**
 * Write a minimal `*.cap.ts` stub under packages/types. Does NOT edit
 * `capabilities/index.ts` or run codegen — those remain explicit next steps
 * (see camstack-capability skill).
 */
export function scaffoldCapStub(options: ScaffoldCapOptions): ScaffoldCapResult {
  const fileName = toFileName(options.name)
  const exportName = toCapExportName(fileName)
  const typeName = `I${toClassName(fileName)}Provider`
  const scope = options.scope ?? 'system'
  const mode = options.mode ?? 'singleton'
  const capsDir = path.join(options.workspaceRoot, 'packages', 'types', 'src', 'capabilities')
  const filePath = path.join(capsDir, `${fileName}.cap.ts`)

  if (!fs.existsSync(capsDir)) {
    throw new Error(`Capabilities directory missing: ${capsDir}`)
  }
  if (fs.existsSync(filePath) && !options.dryRun) {
    throw new Error(`Cap file already exists: ${filePath}`)
  }

  const content = `import { z } from 'zod'
import { type CapabilityDefinition, type InferProvider } from './capability-definition.js'

/**
 * ${fileName} capability stub — generated by \`camstack develop scaffold cap\`.
 *
 * Next steps (required):
 *   1. Fill methods + auth.
 *   2. Re-export from packages/types/src/capabilities/index.ts
 *      and add to the AnyCapability union.
 *   3. npm run codegen
 *   4. Implement + declare the cap by name in the providing addon's manifest.
 */
export const ${exportName} = {
  name: '${fileName}',
  scope: '${scope}',
  mode: '${mode}',
  methods: {
    // ping: {
    //   input: z.object({}),
    //   output: z.object({ ok: z.boolean() }),
    //   auth: 'admin',
    // },
  },
  runtimeState: {
    lastFetchedAt: z.number(),
  },
} as const satisfies CapabilityDefinition

export type ${typeName} = InferProvider<typeof ${exportName}>
`

  if (!options.dryRun) {
    fs.writeFileSync(filePath, content, 'utf8')
  }

  return {
    filePath,
    relativePath: path.relative(options.workspaceRoot, filePath),
    exportName,
    nextSteps: [
      `Edit ${path.relative(options.workspaceRoot, filePath)} — add methods`,
      'Hand-edit packages/types/src/capabilities/index.ts (re-export + AnyCapability)',
      'npm run codegen',
      'Declare the cap by name in the addon manifest and implement the provider',
      'Append ../planning/sessions/<YYYY-MM>.md (sibling clone of github.com/camstack/planning); run npm run docs:check',
    ],
  }
}
